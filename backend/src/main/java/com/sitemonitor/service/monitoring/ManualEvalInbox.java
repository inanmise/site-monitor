/**
 * İzleme değerlendirme gelen kutusu (2026-10-21, çok pod R1-B, MP-14) — {@code monitor_eval_inbox}.
 *
 * <p><b>Neden.</b> Alarm durumu (ardışık sağlıklı sayaç, kardeş izlemenin son DOWN gözlemi, aktif kurtarma zinciri) yalnız
 * TARAMA LİDERİNİN belleğindedir ({@code MonitoringOutageService}). Elle "Şimdi kontrol et" isteği takipçi pod'a düşünce
 * sonuç o pod'un boş belleğinde değerlendiriliyordu: kardeş kuralı atlanıp alarm kapanıyor (sonra yeniden açılıyor), liderin
 * sayacı sıfırlanmıyor, takipçinin kurtarma zinciri iptal edilmiyordu. Takipçi artık ham sonucu buraya yazar; lider
 * {@code SchedulerService.drainManualEvalInbox} ile bugünkü elle kontrol kuralıyla (yalnız kapanış uzlaştırması, alarm
 * AÇMAZ) değerlendirir.
 *
 * <p><b>Tam bir kez.</b> Sahiplenme koşullu UPDATE'tir (PostgreSQL'de tek ifade, {@code FOR UPDATE SKIP LOCKED}); işlemeden
 * hemen önce satır sahibi + kira değeriyle KOŞULLU silinir ({@link #take}) — kirası dolup başka pod'un yeniden sahiplendiği
 * satırı eski sahip işleyemez. Silme ile değerlendirme arasında pod ölürse o elle gözlem kaybolur (zamanlanmış tur
 * kapanışı zaten yapar) — iki kez değerlendirmekten iyidir.
 *
 * <p>Kalıcı adlar (G6): tablo, tür kodları ({@link #TYPE_DNS} …) değiştirilmez.
 */
@Slf4j
@Service
public class ManualEvalInbox {

    public static final String TABLE = "monitor_eval_inbox";

    /** Tablo (H2 + PostgreSQL); varlık ({@code model.MonitorEvalInbox}) ddl-auto ile de kurar — açılış yaması yedektir. */
    public static final String DDL = "CREATE TABLE IF NOT EXISTS monitor_eval_inbox ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "monitor_type VARCHAR(20) NOT NULL, "
            + "monitor_id BIGINT NOT NULL, "
            + "manual BOOLEAN NOT NULL, "
            + "result_json TEXT NOT NULL, "
            + "checked_ms BIGINT NOT NULL, "
            + "source_pod VARCHAR(200), "
            + "claimed_by VARCHAR(200), "
            + "claimed_until_ms BIGINT, "
            + "created_ms BIGINT NOT NULL)";

    public static final String INDEX_DDL =
            "CREATE INDEX IF NOT EXISTS idx_mei_claim ON monitor_eval_inbox(claimed_until_ms, id)";

    public static final String TYPE_DNS = "dns";
    public static final String TYPE_KEYWORD = "keyword";
    public static final String TYPE_PAGE = "page";
    public static final String TYPE_PAGESPEED = "pagespeed";
    public static final String TYPE_SCRIPTED = "scripted";
    public static final String TYPE_PORT = "port";
    public static final String TYPE_PING = "ping";
    public static final String TYPE_HTTP = "http";
    public static final String TYPE_DOMAIN = "domain";

    /** Elle sonucun en eski değerlendirilebilir yaşı — daha eskisi silinir (kullanıcı çoktan başka şey gördü). */
    public static final long STALE_MS = 10L * 60 * 1000;
    /** Sahiplenme kirası: bu sürede işlenmeyen (pod öldü) satır yeniden sahiplenilebilir. */
    public static final long LEASE_MS = 2L * 60 * 1000;
    /** Tek sahiplenmede en çok satır. */
    public static final int CLAIM_BATCH = 25;
    /** JSON tavanı (karakter) — sayfa / senaryo sonucu büyük olabilir; daha büyüğü iletilmez (WARN). */
    static final int MAX_JSON_CHARS = 2_000_000;

    private static final ObjectMapper JSON = JsonMapper.builder().build();
    private static final TypeReference<LinkedHashMap<String, Object>> MAP_TYPE = new TypeReference<>() { };

    private static final String SELECT_COLS =
            "id, monitor_type, monitor_id, manual, result_json, checked_ms, source_pod, claimed_by, claimed_until_ms";

    private static final String SQL_INSERT = "INSERT INTO monitor_eval_inbox "
            + "(monitor_type, monitor_id, manual, result_json, checked_ms, source_pod, created_ms) VALUES (?, ?, ?, ?, ?, ?, ?)";

    /** PostgreSQL: tek ifadede sahiplen + satırları döndür; kilitli satırı atla (iki lider aynı anda boşaltsa da çakışmaz). */
    private static final String SQL_CLAIM_PG = "UPDATE monitor_eval_inbox SET claimed_by = ?, claimed_until_ms = ? "
            + "WHERE id IN (SELECT id FROM monitor_eval_inbox WHERE claimed_until_ms IS NULL OR claimed_until_ms < ? "
            + "ORDER BY id LIMIT ? FOR UPDATE SKIP LOCKED) RETURNING " + SELECT_COLS;

    private static final String SQL_CANDIDATES = "SELECT " + SELECT_COLS + " FROM monitor_eval_inbox "
            + "WHERE claimed_until_ms IS NULL OR claimed_until_ms < ? ORDER BY id LIMIT ?";

    private static final String SQL_CAS = "UPDATE monitor_eval_inbox SET claimed_by = ?, claimed_until_ms = ? "
            + "WHERE id = ? AND (claimed_until_ms IS NULL OR claimed_until_ms < ?)";

    private static final String SQL_TAKE = "DELETE FROM monitor_eval_inbox WHERE id = ? AND claimed_by = ? AND claimed_until_ms = ?";

    /** Bir satır. {@code claimedBy}/{@code claimedUntilMs}: bu pod'un sahiplendiği değerler ({@link #take} için). */
    public record Row(long id, String type, long monitorId, boolean manual, String resultJson, long checkedMs,
                      String sourcePod, String claimedBy, long claimedUntilMs) {
        @Override
        public String toString() {   // sonuç gövdesi günlüğe düşmesin
            return "Row[id=" + id + ", type=" + type + ", monitorId=" + monitorId + ", manual=" + manual + "]";
        }
    }

    private static final RowMapper<Row> ROW = (rs, i) -> new Row(rs.getLong("id"), rs.getString("monitor_type"),
            rs.getLong("monitor_id"), rs.getBoolean("manual"), rs.getString("result_json"), rs.getLong("checked_ms"),
            rs.getString("source_pod"), rs.getString("claimed_by"), rs.getLong("claimed_until_ms"));

    private final JdbcTemplate jdbc;
    private volatile LongSupplier clock = System::currentTimeMillis;
    /** Lehçe bilgisi: TRUE PostgreSQL, FALSE başka (H2), null henüz bilinmiyor / okunamadı (her seferinde yeniden sorulur). */
    private volatile Boolean postgres;
    /** Kira değerleri aynı milisaniyede çakışmasın (aynı pod'un ardışık sahiplenmeleri). */
    private final AtomicLong lastLease = new AtomicLong();
    private final AtomicLong warnAt = new AtomicLong();

    @Autowired
    public ManualEvalInbox(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    /** Test: ortak saat. */
    public void setClock(LongSupplier clock) {
        this.clock = clock == null ? System::currentTimeMillis : clock;
    }

    public long now() {
        return clock.getAsLong();
    }

    /**
     * Ham elle kontrol sonucunu lider için kuyruğa yazar.
     *
     * @return yazıldıysa true; JSON'a çevrilemedi / çok büyük / tablo yok / DB hatası → false (WARN; çağıran YEREL
     *         değerlendirme YAPMAZ — takipçinin belleği boş)
     */
    public boolean enqueue(String type, long monitorId, boolean manual, Map<String, Object> raw, String sourcePod) {
        String json;
        try {
            json = toJson(raw);
        } catch (RuntimeException e) {
            warn("Elle kontrol sonucu lider pod'a iletilemedi (JSON'a çevrilemedi): tür={} izleme={} — {}", type, monitorId,
                    e.toString());
            return false;
        }
        if (json.length() > MAX_JSON_CHARS) {
            warn("Elle kontrol sonucu lider pod'a iletilmedi (çok büyük, {} karakter): tür={} izleme={}", json.length(),
                    type, monitorId);
            return false;
        }
        long now = now();
        try {
            jdbc.update(SQL_INSERT, type, monitorId, manual, json, now, sourcePod, now);
            return true;
        } catch (RuntimeException e) {
            warn("Elle kontrol sonucu lider pod'a iletilemedi (gelen kutusu yazılamadı): tür={} izleme={} — {}", type,
                    monitorId, e.toString());
            return false;
        }
    }

    /**
     * Gelen kutusunda bekleyen satır sayısı (2026-10-23, çok pod R2b) — {@code sitemonitor_eval_inbox_depth} küme ölçümü; tek
     * {@code COUNT(*)} (küçük tablo: lider 5 sn'de bir boşaltır, 10 dk'dan eski satırı atar). Tablo yok / DB hatası → istisna
     * (ölçüm aktarıcısı kaynağı "okunamadı" sayar, sahte 0 yazmaz).
     */
    public long depth() {
        Long n = jdbc.queryForObject("SELECT COUNT(*) FROM " + TABLE, Long.class);
        return n == null ? 0L : n;
    }

    /**
     * En çok {@code limit} satırı bu sahip adına {@link #LEASE_MS} süreyle sahiplenir. Kirası dolmuş (sahibi ölmüş) satır da
     * sahiplenilebilir. Hata → boş liste (sonraki turda yeniden denenir).
     */
    public List<Row> claim(String owner, int limit) {
        long now = now();
        long until = nextLease(now + LEASE_MS);
        int n = Math.max(1, Math.min(limit, 500));
        if (Boolean.TRUE.equals(postgres())) {
            try {
                return jdbc.query(SQL_CLAIM_PG, ROW, owner, until, now, n);
            } catch (RuntimeException e) {
                log.debug("Gelen kutusu tek ifadeli sahiplenme düştü, satır satır deneniyor: {}", e.toString());
            }
        }
        List<Row> out = new ArrayList<>();
        try {
            for (Row r : jdbc.query(SQL_CANDIDATES, ROW, now, n)) {
                if (jdbc.update(SQL_CAS, owner, until, r.id(), now) == 1) {
                    out.add(new Row(r.id(), r.type(), r.monitorId(), r.manual(), r.resultJson(), r.checkedMs(),
                            r.sourcePod(), owner, until));
                }
            }
        } catch (RuntimeException e) {
            warn("Elle kontrol gelen kutusu okunamadı (sonraki turda yeniden denenecek): {}", e.toString());
        }
        return out;
    }

    /**
     * Sahiplenilen satırı işlemeden hemen önce KOŞULLU siler: hâlâ bu sahip + bu kira değerindeyse true (bu pod işler),
     * değilse false (kira dolup başka pod sahiplendi — işleme). Hata → false.
     */
    public boolean take(Row row) {
        try {
            return jdbc.update(SQL_TAKE, row.id(), row.claimedBy(), row.claimedUntilMs()) == 1;
        } catch (RuntimeException e) {
            warn("Elle kontrol gelen kutusu satırı alınamadı (id={}): {}", row.id(), e.toString());
            return false;
        }
    }

    private static final String SQL_ADVERTISE_UPDATE = "UPDATE " + com.sitemonitor.service.schedule.ClusterScheduleService.TABLE
            + " SET next_due_at = ?, claimed_by = ?, claimed_at = ? WHERE monitor_key = ?";
    private static final String SQL_ADVERTISE_INSERT = "INSERT INTO " + com.sitemonitor.service.schedule.ClusterScheduleService.TABLE
            + "(monitor_key, next_due_at, claimed_by, claimed_at) VALUES (?, ?, ?, ?) ON CONFLICT DO NOTHING";

    /**
     * Boşaltıcı ilanı (inceleme 2026-10-22, B1): {@code monitor_check_schedule} satırı {@code lease:<name>} = "bu sahibin kodu
     * gelen kutusunu boşaltır". Tarama lideri KOŞULSUZ yazar (önceki liderin — ölmüş olsa da — satırını beklemeden devralır);
     * takipçi satırın sahibini tarama liderliği kirasının sahibiyle karşılaştırır. Kira semantiği yok: tek yazan liderdir.
     *
     * @return yazıldı mı (hata yutulur — takipçiler o sürede yerel değerlendirir)
     */
    public boolean advertiseDrainer(String name, String owner, long nowMs, long untilMs) {
        String key = com.sitemonitor.service.schedule.ClusterScheduleService.LEASE_PREFIX + name;
        try {
            if (jdbc.update(SQL_ADVERTISE_UPDATE, untilMs, owner, nowMs, key) == 1) return true;
            return jdbc.update(SQL_ADVERTISE_INSERT, key, untilMs, owner, nowMs) == 1;
        } catch (RuntimeException e) {
            warn("Gelen kutusu boşaltıcı ilanı yazılamadı (takipçiler bu sürede elle kontrolü yerel değerlendirir): {}",
                    e.toString());
            return false;
        }
    }

    /** Satırın ham sonucu (değiştirilebilir harita). */
    public static Map<String, Object> parse(String json) {
        if (json == null || json.isBlank()) return new LinkedHashMap<>();
        return JSON.readValue(json, MAP_TYPE);
    }

    /** JSON'a çevirir; Jackson'ın tanımadığı bir değer varsa ağacı önce düz türlere indirger. */
    public static String toJson(Map<String, Object> raw) {
        Map<String, Object> m = raw == null ? Map.of() : raw;
        try {
            return JSON.writeValueAsString(m);
        } catch (RuntimeException e) {
            return JSON.writeValueAsString(plain(m, 0));
        }
    }

    /** Değeri JSON'un düz türlerine indirger (harita / liste / sayı / mantıksal / metin); derinlik tavanlı. */
    static Object plain(Object v, int depth) {
        if (v == null || v instanceof String || v instanceof Number || v instanceof Boolean) return v;
        if (depth > 32) return "…";   // derinlik tavanı (döngülü yapı toString'de taşmasın)
        if (v instanceof Map<?, ?> map) {
            Map<String, Object> out = new LinkedHashMap<>();
            for (Map.Entry<?, ?> e : map.entrySet()) out.put(String.valueOf(e.getKey()), plain(e.getValue(), depth + 1));
            return out;
        }
        if (v instanceof Collection<?> c) {
            List<Object> out = new ArrayList<>(c.size());
            for (Object o : c) out.add(plain(o, depth + 1));
            return out;
        }
        if (v.getClass().isArray()) {
            int len = Array.getLength(v);
            List<Object> out = new ArrayList<>(len);
            for (int i = 0; i < len; i++) out.add(plain(Array.get(v, i), depth + 1));
            return out;
        }
        if (v instanceof Enum<?> en) return en.name();
        return String.valueOf(v);
    }

    private long nextLease(long candidate) {
        while (true) {
            long prev = lastLease.get();
            long next = Math.max(candidate, prev + 1);
            if (lastLease.compareAndSet(prev, next)) return next;
        }
    }

    private Boolean postgres() {
        Boolean p = postgres;
        if (p != null) return p;
        p = com.sitemonitor.service.schema.DeferredIndexBuilder.postgresOrNull(jdbc.getDataSource());
        if (p != null) postgres = p;
        return p;
    }

    private void warn(String fmt, Object... args) {
        long last = warnAt.get();
        long now = System.currentTimeMillis();
        if (now - last >= 60_000L && warnAt.compareAndSet(last, now)) log.warn(fmt, args);
        else log.debug(fmt, args);
    }
}
