package com.sitemonitor.service.checks;

import com.sitemonitor.service.schedule.ClusterScheduleService;

import java.util.Collections;
import java.util.List;

/**
 * Dağıtık kontrol kuyruğunun DDL'i ve SQL'i (2026-10-29, çok pod Sürüm 3-3 paket A; tasarım R3-3 §3.1 / §3.2). Entity YOK —
 * iki ham tablo {@link CheckJobSchemaPatch} ile açılışta kurulur; yazımlar işlem DIŞINDA (otomatik commit) koşar: bir
 * PostgreSQL hatası hiçbir çağıranın işlemini bozamaz (25P02).
 *
 * <p><b>Tablolar (adlar KALICI — yayından sonra yeniden adlandırılmaz):</b>
 * <ul>
 *   <li>{@link #JOBS} — kontrol işi başına bir satır: PENDING (gönderildi) → CLAIMED (işçi sahiplendi) → DONE (sonuç yazıldı)
 *       → değerlendiricinin {@code take} çağrısıyla silinir. Bir izlemenin aynı anda en çok bir AÇIK (PENDING / CLAIMED) işi
 *       olur: PostgreSQL'de kısmi tekil dizin {@link #DDL_OPEN_UNIQUE_PG} ({@code ON CONFLICT DO NOTHING}), H2 / bilinmeyen
 *       türde {@code INSERT … SELECT … WHERE NOT EXISTS} (tek gönderen = tarama lideri).</li>
 *   <li>{@link #WORKERS} — işçi (pod örneği) başına bir satır; anahtar açıkken 10 sn'de bir kalp atışı.</li>
 * </ul>
 * Tüm zaman sütunları VERİTABANI-ÇAPALI saatle ({@link DbClock}) ms'dir. {@code result_json} asla günlüğe yazılmaz (sayfa
 * metni / k6 çıktısı taşıyabilir).
 */
public final class CheckJobSql {

    private CheckJobSql() {
    }

    /** Kontrol işi kuyruğu — kalıcı ad. */
    public static final String JOBS = "monitor_check_jobs";
    /** Kontrol işçileri kaydı — kalıcı ad. */
    public static final String WORKERS = "monitor_check_workers";
    /** İki tablo, kurulum sırasıyla. */
    public static final List<String> TABLES = List.of(JOBS, WORKERS);

    /** Kuyruk / kayıt ifadelerinin sorgu zaman aşımı (sn) — bir kilit beklemesi yoklama / boşaltma iş parçacığını uzun süre tutmasın. */
    public static final int QUERY_TIMEOUT_SECONDS = 10;
    /** PostgreSQL çok satırlı gönderme / H2 toplu gönderme parçası. */
    public static final int DISPATCH_CHUNK = 200;
    /** Tek sahiplenme / alma / biçmede en çok satır. */
    public static final int MAX_BATCH = 500;
    /** {@code claim_token} uzunluğu üst sınırı. */
    public static final int TOKEN_MAX = 40;
    /** Örnek kimliği / pod adı sütunlarının uzunluğu. */
    public static final int INSTANCE_MAX = 200;
    /** {@code version} sütun uzunluğu. */
    public static final int VERSION_MAX = 40;
    /** {@code caps} sütun uzunluğu. */
    public static final int CAPS_MAX = 200;

    /** Tarama lideri kirasının {@code monitor_check_schedule} anahtarı (kira-bağlı alma) — {@code EvalStateSql.LEASE_KEY} ile aynı. */
    public static final String LEASE_KEY = ClusterScheduleService.LEASE_PREFIX + "sweep-leader";

    // ── DDL ─────────────────────────────────────────────────────────────────────────────────────────────────────────

    /** Kuyruk tablosu (H2 + PostgreSQL; kimlik biçimi {@code monitor_eval_inbox} ile aynı). */
    public static final String DDL_JOBS = "CREATE TABLE IF NOT EXISTS " + JOBS + " ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "job_type VARCHAR(20) NOT NULL, "
            + "monitor_id BIGINT NOT NULL, "
            + "state VARCHAR(10) NOT NULL, "
            + "lease_ms BIGINT NOT NULL, "
            + "created_ms BIGINT NOT NULL, "
            + "dispatcher VARCHAR(200) NOT NULL, "
            + "attempts INT NOT NULL, "
            + "claimed_by VARCHAR(200), "
            + "claim_token VARCHAR(40), "
            + "claimed_ms BIGINT, "
            + "lease_until_ms BIGINT, "
            + "finished_ms BIGINT, "
            + "worker VARCHAR(200), "
            + "result_json TEXT, "
            + "result_truncated BOOLEAN)";

    /** Durum + sıra dizini (sahiplenme, alma, biçme, kuyruk özeti) — tablo ile birlikte, boşken kurulur. */
    public static final String DDL_STATE_INDEX = "CREATE INDEX IF NOT EXISTS idx_mcj_state ON " + JOBS + "(state, id)";

    /** Yalnız PostgreSQL: izleme başına en çok bir AÇIK iş (tablo ile birlikte, boşken kurulur; ertelenmiş katalogda DEĞİL). */
    public static final String DDL_OPEN_UNIQUE_PG = "CREATE UNIQUE INDEX IF NOT EXISTS ux_mcj_open ON " + JOBS
            + "(job_type, monitor_id) WHERE state IN ('PENDING','CLAIMED')";
    /** {@link #DDL_OPEN_UNIQUE_PG} dizininin adı. */
    public static final String OPEN_UNIQUE_INDEX = "ux_mcj_open";

    /**
     * Yalnız PostgreSQL: sıcak, küçük kuyruk tablosunda sabit eşikli otomatik süpürme (ölü satır oranı değil, 2000 ölü satır)
     * — {@code SchemaDdlGuard} {@code SET (reloptions)} biçimini tanır, her açılışta zaten varsa kilitsiz atlanır.
     */
    public static final String RELOPTIONS_PG = "ALTER TABLE " + JOBS
            + " SET (autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 2000)";

    /** İşçi kaydı tablosu. */
    public static final String DDL_WORKERS = "CREATE TABLE IF NOT EXISTS " + WORKERS + " ("
            + "instance_id VARCHAR(200) NOT NULL PRIMARY KEY, "
            + "pod VARCHAR(200), "
            + "caps VARCHAR(200), "
            + "slots INT, "
            + "busy INT, "
            + "completed BIGINT, "
            + "late BIGINT, "
            + "claim_lag_p95_ms BIGINT, "
            + "heartbeat_ms BIGINT NOT NULL, "
            + "version VARCHAR(40), "
            + "stopping BOOLEAN)";

    // ── Kuyruk SQL'i ────────────────────────────────────────────────────────────────────────────────────────────────

    private static final String INSERT_COLS =
            "INSERT INTO " + JOBS + " (job_type, monitor_id, state, lease_ms, created_ms, dispatcher, attempts) ";

    /**
     * Taşınabilir gönderme (H2 / bilinmeyen tür ya da PostgreSQL'de tekil dizin yokken): satır başına "açık işi yoksa ekle".
     * Parametreler: tür, izleme, kira, oluşturma, gönderen, tür, izleme.
     */
    public static final String SQL_DISPATCH_ONE = INSERT_COLS
            + "SELECT CAST(? AS VARCHAR(20)), CAST(? AS BIGINT), 'PENDING', CAST(? AS BIGINT), CAST(? AS BIGINT), "
            + "CAST(? AS VARCHAR(200)), 0 WHERE NOT EXISTS (SELECT 1 FROM " + JOBS
            + " WHERE job_type = ? AND monitor_id = ? AND state IN ('PENDING','CLAIMED'))";

    /** PostgreSQL çok satırlı gönderme ({@code rows} satırlık VALUES; satır başına 5 parametre) — tekil dizinle çakışan atlanır. */
    public static String dispatchMultiRowPg(int rows) {
        StringBuilder sb = new StringBuilder(INSERT_COLS).append("VALUES ");
        for (int i = 0; i < rows; i++) {
            if (i > 0) sb.append(", ");
            sb.append("(?, ?, 'PENDING', ?, ?, ?, 0)");
        }
        return sb.append(" ON CONFLICT DO NOTHING").toString();
    }

    /** Sahiplenme sonucu sütunları (her iki yol aynı sırayla okur). */
    public static final String CLAIM_COLS =
            "id, job_type, monitor_id, created_ms, attempts, lease_ms, claim_token, claimed_ms, lease_until_ms";

    /**
     * Aday koşulu: türler, PENDING ya da kirası dolmuş CLAIMED, deneme tavanı altı (+ isteğe bağlı oluşturma eşiği).
     * Parametre sırası: türler…, şimdi, deneme tavanı [, oluşturma eşiği].
     */
    static String candidateWhere(int types, boolean createdFilter) {
        return "job_type IN (" + placeholders(types) + ") "
                + "AND (state = 'PENDING' OR (state = 'CLAIMED' AND lease_until_ms < ?)) "
                + "AND attempts < ?"
                + (createdFilter ? " AND created_ms < ?" : "");
    }

    /**
     * PostgreSQL tek ifadeli sahiplenme ({@code FOR UPDATE SKIP LOCKED} — iki işçi aynı satırı alamaz). Parametreler: sahip,
     * belirteç, şimdi, şimdi (kira tabanı), [aday koşulu], limit.
     */
    public static String claimPg(int types, boolean createdFilter) {
        return "UPDATE " + JOBS + " SET state = 'CLAIMED', claimed_by = ?, claim_token = ?, claimed_ms = ?, "
                + "lease_until_ms = CAST(? AS BIGINT) + lease_ms, attempts = attempts + 1 "
                + "WHERE id IN (SELECT id FROM " + JOBS + " WHERE " + candidateWhere(types, createdFilter)
                + " ORDER BY id LIMIT ? FOR UPDATE SKIP LOCKED) RETURNING " + CLAIM_COLS;
    }

    /** Taşınabilir sahiplenme 1. adım: adaylar (kilitsiz). Parametreler: [aday koşulu], limit. */
    public static String claimCandidates(int types, boolean createdFilter) {
        return "SELECT id, job_type, monitor_id, created_ms, attempts, lease_ms FROM " + JOBS + " WHERE "
                + candidateWhere(types, createdFilter) + " ORDER BY id LIMIT ?";
    }

    /**
     * Taşınabilir sahiplenme 2. adım: satır başına CAS (okunan deneme sayısı + hâlâ sahiplenilebilir). Parametreler: sahip,
     * belirteç, şimdi, şimdi (kira tabanı), id, okunan deneme, şimdi.
     */
    public static final String SQL_CLAIM_CAS = "UPDATE " + JOBS + " SET state = 'CLAIMED', claimed_by = ?, claim_token = ?, "
            + "claimed_ms = ?, lease_until_ms = CAST(? AS BIGINT) + lease_ms, attempts = attempts + 1 "
            + "WHERE id = ? AND attempts = ? AND (state = 'PENDING' OR (state = 'CLAIMED' AND lease_until_ms < ?))";

    /**
     * Tamamlama (JDBC toplu): yalnız hâlâ BU sahiplenmenin belirteciyle CLAIMED satır. Parametreler: sonuç, kırpıldı, bitiş,
     * işçi, id, belirteç.
     */
    public static final String SQL_COMPLETE = "UPDATE " + JOBS + " SET state = 'DONE', result_json = ?, result_truncated = ?, "
            + "finished_ms = ?, worker = ?, lease_until_ms = NULL WHERE id = ? AND state = 'CLAIMED' AND claim_token = ?";

    /** Bırakma: başlamamış sahiplenmeler PENDING'e (deneme bir geri). Parametreler: sahip, id'ler… */
    public static String release(int ids) {
        return "UPDATE " + JOBS + " SET state = 'PENDING', claimed_by = NULL, claim_token = NULL, claimed_ms = NULL, "
                + "lease_until_ms = NULL, attempts = CASE WHEN attempts > 0 THEN attempts - 1 ELSE 0 END "
                + "WHERE claimed_by = ? AND state = 'CLAIMED' AND id IN (" + placeholders(ids) + ")";
    }

    /** Alma sonuç sütunları. */
    public static final String TAKE_COLS =
            "id, job_type, monitor_id, created_ms, claimed_ms, finished_ms, worker, result_json, result_truncated";

    private static final String LEASE_EXISTS = "EXISTS (SELECT 1 FROM " + ClusterScheduleService.TABLE
            + " WHERE monitor_key = '" + LEASE_KEY + "' AND claimed_by = ?)";

    /**
     * PostgreSQL kira-bağlı alma: DONE satırları id sırasında, kilitli olanı atla; kirayı kaybetmiş pod hiçbir şey almaz.
     * Parametreler: limit, kira sahibi.
     */
    public static final String SQL_TAKE_PG = "DELETE FROM " + JOBS + " WHERE id IN (SELECT id FROM " + JOBS
            + " WHERE state = 'DONE' ORDER BY id LIMIT ? FOR UPDATE SKIP LOCKED) AND " + LEASE_EXISTS
            + " RETURNING " + TAKE_COLS;

    /** Taşınabilir alma 1. adım: DONE satırlar (kilitsiz). Parametre: limit. */
    public static final String SQL_TAKE_CANDIDATES = "SELECT " + TAKE_COLS + " FROM " + JOBS
            + " WHERE state = 'DONE' ORDER BY id LIMIT ?";

    /** Taşınabilir alma 2. adım: satır başına kira-bağlı koşullu silme. Parametreler: id, kira sahibi. */
    public static final String SQL_TAKE_ONE = "DELETE FROM " + JOBS + " WHERE id = ? AND state = 'DONE' AND " + LEASE_EXISTS;

    /** Biçme adayları: kirası dolmuş, deneme tavanına ulaşmış sahiplenmeler. Parametreler: şimdi, tavan, limit. */
    public static final String SQL_REAP_CANDIDATES = "SELECT id, job_type, monitor_id, created_ms, attempts, lease_ms FROM "
            + JOBS + " WHERE state = 'CLAIMED' AND lease_until_ms < ? AND attempts >= ? ORDER BY id LIMIT ?";

    /** Biçme: satır başına koşullu silme (aday hâlâ aynı durumda). Parametreler: id, şimdi, tavan. */
    public static final String SQL_REAP_ONE = "DELETE FROM " + JOBS
            + " WHERE id = ? AND state = 'CLAIMED' AND lease_until_ms < ? AND attempts >= ?";

    /** Kuyruk özeti: durum × tür başına sayı + en eski oluşturma / bitiş + kirası dolmuş sahiplenme. Parametre: şimdi. */
    public static final String SQL_STATS = "SELECT state, job_type, COUNT(*) AS n, MIN(created_ms) AS min_created, "
            + "MIN(finished_ms) AS min_finished, "
            + "SUM(CASE WHEN state = 'CLAIMED' AND lease_until_ms < ? THEN 1 ELSE 0 END) AS expired "
            + "FROM " + JOBS + " GROUP BY state, job_type";

    /** PostgreSQL: tekil açık iş dizini var mı. */
    public static final String SQL_OPEN_INDEX_PRESENT_PG = "SELECT to_regclass('" + OPEN_UNIQUE_INDEX + "') IS NOT NULL";

    // ── İşçi kaydı SQL'i ────────────────────────────────────────────────────────────────────────────────────────────

    /** İşçi satırı sütunları (okuma). */
    public static final String WORKER_COLS =
            "instance_id, pod, caps, slots, busy, completed, late, claim_lag_p95_ms, heartbeat_ms, version, stopping";

    /** PostgreSQL kalp atışı: tek ifadeli upsert. Parametreler: {@link #WORKER_COLS} sırasıyla 11 değer. */
    public static final String SQL_HEARTBEAT_PG = "INSERT INTO " + WORKERS + " (" + WORKER_COLS + ") "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT (instance_id) DO UPDATE SET pod = EXCLUDED.pod, "
            + "caps = EXCLUDED.caps, slots = EXCLUDED.slots, busy = EXCLUDED.busy, completed = EXCLUDED.completed, "
            + "late = EXCLUDED.late, claim_lag_p95_ms = EXCLUDED.claim_lag_p95_ms, heartbeat_ms = EXCLUDED.heartbeat_ms, "
            + "version = EXCLUDED.version, stopping = EXCLUDED.stopping";

    /** Taşınabilir kalp atışı 1. adım: güncelle. Parametreler: pod, caps, slots, busy, completed, late, p95, nabız, sürüm, durma, kimlik. */
    public static final String SQL_HEARTBEAT_UPDATE = "UPDATE " + WORKERS + " SET pod = ?, caps = ?, slots = ?, busy = ?, "
            + "completed = ?, late = ?, claim_lag_p95_ms = ?, heartbeat_ms = ?, version = ?, stopping = ? WHERE instance_id = ?";

    /** Taşınabilir kalp atışı 2. adım: yoksa ekle (yarışta hiçbir şey yapma → 1. adım yeniden). */
    public static final String SQL_HEARTBEAT_INSERT = "INSERT INTO " + WORKERS + " (" + WORKER_COLS + ") "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT DO NOTHING";

    /** Kapanış: kendi satırını "duruyor" işaretle. Parametreler: nabız, kimlik. */
    public static final String SQL_MARK_STOPPING = "UPDATE " + WORKERS
            + " SET stopping = TRUE, busy = 0, heartbeat_ms = ? WHERE instance_id = ?";

    /** Tüm işçiler (en yeni nabız önce, tavanlı). Parametre: limit. */
    public static final String SQL_WORKERS = "SELECT " + WORKER_COLS + " FROM " + WORKERS + " ORDER BY heartbeat_ms DESC LIMIT ?";

    /** Budama: bu andan eski nabızlı satırlar. Parametre: eşik. */
    public static final String SQL_PRUNE_WORKERS = "DELETE FROM " + WORKERS + " WHERE heartbeat_ms < ?";

    /** {@code n} adet "?" virgülle. */
    static String placeholders(int n) {
        return String.join(", ", Collections.nCopies(Math.max(1, n), "?"));
    }
}
