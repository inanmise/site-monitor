package com.sitemonitor.service.baseline;

import com.sitemonitor.service.baseline.BaselineMath.History;
import com.sitemonitor.service.baseline.BaselineMath.Sample;
import com.sitemonitor.service.evalstate.EvalStateSql;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.BadSqlGrammarException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

/**
 * Dinamik taban çizgisinin örnek deposu (2026-11-12) — ÇOK POD: tarama lideri, taban çizgisi AÇIK bir izlemenin her
 * ZAMANLANMIŞ kontrolünde bir örnek (yanıt süresi + bu değerin tabanı ihlal edip etmediği) ekler; değerlendirici bantı bu
 * tablodan okur. Tek tablo tüm türler için ({@code CheckJobSql} / {@code EvalStateSql} deseni; entity yok) — değerlendirici
 * türden bağımsızdır. Elle / teyit / kurtarma kontrolleri örnek YAZMAZ (çağıran yalnız zamanlanmış sonuçta ekler), böylece
 * teyit zinciri boyunca yeni örnek girmez ve bant sabit kalır (ayrı çapa gerekmez; dbquery'nin elle/recheck dışlamasıyla
 * aynı amaç).
 *
 * <p>Her ifade KENDİ sorgu zaman aşımlı şablonunda ({@value #QUERY_TIMEOUT_SECONDS} sn) ve sınıf düzeyinde
 * {@code @Transactional(NOT_SUPPORTED)} — çağıranın (tarama) işlemine katılmaz, bir PostgreSQL hatası onu bozamaz. Tablo
 * yoksa (ilk açılışın ilk saniyeleri) okuma boş, ekleme sessiz atlar; {@link BaselineSchemaPatch} hazır olduğunu bildirince
 * ({@link #markReady}) açılır. Okuma: mevsimsiz en yeni N örnek ({@link #readRecent}) ya da mevsimsel ({@link #readSeasonal}).</p>
 */
@Slf4j
@Component
@Transactional(propagation = Propagation.NOT_SUPPORTED)
public class BaselineSampleStore {

    /** Tablo adı — KALICI (yayından sonra yeniden adlandırılmaz). */
    public static final String TABLE = "monitor_baseline_samples";
    public static final int QUERY_TIMEOUT_SECONDS = 10;
    /**
     * İzleme başına budamada her zaman tutulan en yeni satır sayısı. Mevsimsiz okuma pencere üst sınırının (200) iki katını
     * ({@code recentNeed}) ister — bu sınır yeter. MEVSİMSEL okuma en az bir periyot önceki, günün/haftanın aynı saatine düşen
     * örnekleri toplar; bunun için satır sınırı yetmez (30 sn aralıkta 1500 satır 12,5 saattir) — budama mevsimsel izlemede ayrıca
     * {@link #seasonalKeepFromMs} süresini korur (hata taraması 2026-11-13, son inceleme).
     */
    public static final int KEEP_PER_MONITOR = 1500;

    /** Mevsimsel pencere uzunlukları. */
    public static final long DAY_MS = 86_400_000L, WEEK_MS = 7L * DAY_MS;
    /** Mevsimsel eşleşme toleransının alt sınırı (± dk, ms): aynı "saat" ±30 dk — saatlik örüntüyü birkaç örnekle yakalar. */
    public static final long SEASON_TOLERANCE_MIN_MS = 1_800_000L;

    public static final String DDL_TABLE = "CREATE TABLE IF NOT EXISTS " + TABLE + " ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "monitor_type VARCHAR(16) NOT NULL, "
            + "monitor_id BIGINT NOT NULL, "
            + "checked_ms BIGINT NOT NULL, "
            + "value_ms BIGINT NOT NULL, "
            + "breach BOOLEAN NOT NULL, "
            + "created_ms BIGINT NOT NULL)";

    /** En yeni N örnek okuması ve budama bu dizini kullanır. */
    public static final String DDL_INDEX =
            "CREATE INDEX IF NOT EXISTS idx_mbs_monitor ON " + TABLE + " (monitor_type, monitor_id, checked_ms)";

    private final JdbcTemplate jdbc;
    /** Budamanın uzun zaman aşımlı şablonu (yalnız günlük budama işi; tarama yolu {@link #jdbc} — 10 sn). */
    private final JdbcTemplate pruneJdbc;
    private volatile boolean ready;

    public BaselineSampleStore(JdbcTemplate jdbc) {
        this.jdbc = jdbc == null ? null : EvalStateSql.withQueryTimeout(jdbc, QUERY_TIMEOUT_SECONDS);
        this.pruneJdbc = jdbc == null ? null : EvalStateSql.withQueryTimeout(jdbc, PRUNE_QUERY_TIMEOUT_SECONDS);
    }

    /** {@link BaselineSchemaPatch} tabloyu kurunca çağrılır. */
    public void markReady(boolean value) {
        this.ready = value;
    }

    public boolean ready() {
        return ready;
    }

    /** Bir zamanlanmış örnek ekler (değer + bu değerin tabanı ihlali). Tablo yoksa sessiz atlar (örnek kaybı önemsiz). */
    public void append(String type, long monitorId, long checkedMs, long valueMs, boolean breach) {
        if (jdbc == null || !BaselineTypes.supported(type)) return;
        try {
            jdbc.update("INSERT INTO " + TABLE + " (monitor_type, monitor_id, checked_ms, value_ms, breach, created_ms) "
                    + "VALUES (?, ?, ?, ?, ?, ?)", type, monitorId, checkedMs, valueMs, breach, System.currentTimeMillis());
        } catch (BadSqlGrammarException missing) {
            ready = false;   // tablo henüz yok
        } catch (RuntimeException e) {
            log.debug("Taban çizgisi örneği eklenemedi ({}#{}): {}", type, monitorId, e.getMessage());
        }
    }

    /**
     * {@code beforeMs}'ten (hariç) önceki en yeni örnekler, YENİDEN ESKİYE (ihlal bayrağıyla). {@code complete} = sınıra
     * değilmedi (geçmişin tamamı okundu — kontrollü uyumun "geçmişi kaplıyor" kolu bunu ister).
     */
    public History readRecent(String type, long monitorId, long beforeMs, int limit) {
        if (jdbc == null || !BaselineTypes.supported(type) || limit <= 0) return History.EMPTY;
        try {
            List<Sample> rows = jdbc.query(
                    "SELECT value_ms, breach FROM " + TABLE + " WHERE monitor_type = ? AND monitor_id = ? "
                            + "AND checked_ms < ? ORDER BY checked_ms DESC, id DESC LIMIT ?",
                    (rs, n) -> new Sample(rs.getLong(1), rs.getBoolean(2)), type, monitorId, beforeMs, limit);
            boolean complete = rows.size() < limit;   // sınıra değmedi = hepsi okundu
            return new History(rows, complete, false);
        } catch (BadSqlGrammarException missing) {
            ready = false;
            return History.EMPTY;
        } catch (RuntimeException e) {
            log.debug("Taban çizgisi geçmişi okunamadı ({}#{}): {}", type, monitorId, e.getMessage());
            return History.EMPTY;
        }
    }

    /**
     * MEVSİMSEL okuma: EN AZ BİR PERİYOT ÖNCEKİ (dün / geçen hafta ve öncesi), günün/haftanın AYNI konumuna (saatine)
     * ± {@code toleranceMs} düşen en yeni {@code limit} örnek, yeniden eskiye. Üst sınır {@code beforeMs − periodMs +
     * toleranceMs}: bugünün (bu haftanın) son yarım saatindeki örnekler "aynı saat" SAYILMAZ — aksi hâlde kısa aralıklı izlemede
     * pencere tamamen son 30 dakikadan dolar ve mevsimsellik fiilen mevsimsiz olurdu (hata taraması 2026-11-13 #3). Dairesel
     * uzaklık {@code LEAST(|Δ|, period−|Δ|)} ile hesaplanır (gün sonu ↔ gün başı sarması doğru). {@code complete=false}
     * (muhafazakâr): mevsimsel geçmişin tamamı okunmadı varsayılır — kontrollü uyumun "geçmişi kaplıyor" kolu mevsimselde
     * devre dışı kalır, yalnız {@code window} uzunluğundaki ihlal dizisi uyum sağlar. {@code nowPos} = {@code beforeMs}'in
     * periyot içindeki konumu (çağıran hesaplar). H2 + PostgreSQL ortak: {@code MOD/ABS/LEAST}.
     */
    public History readSeasonal(String type, long monitorId, long beforeMs, int limit,
                                long periodMs, long nowPos, long toleranceMs) {
        if (jdbc == null || !BaselineTypes.supported(type) || limit <= 0 || periodMs <= 0) return History.EMPTY;
        // En az bir periyot önceki örnekler: dünün aynı saatinin ±tol penceresinin en yeni ucu (before − period + tol)
        long upper = Math.min(beforeMs - 1, beforeMs - periodMs + Math.max(0, toleranceMs));
        try {
            List<Sample> rows = jdbc.query(
                    "SELECT value_ms, breach FROM " + TABLE + " WHERE monitor_type = ? AND monitor_id = ? "
                            + "AND checked_ms <= ? "
                            + "AND LEAST(ABS(MOD(checked_ms, ?) - ?), ? - ABS(MOD(checked_ms, ?) - ?)) <= ? "
                            + "ORDER BY checked_ms DESC, id DESC LIMIT ?",
                    (rs, n) -> new Sample(rs.getLong(1), rs.getBoolean(2)),
                    type, monitorId, upper, periodMs, nowPos, periodMs, periodMs, nowPos, toleranceMs, limit);
            return new History(rows, false, false);   // complete=false (muhafazakâr) — bkz. javadoc
        } catch (BadSqlGrammarException missing) {
            ready = false;
            return History.EMPTY;
        } catch (RuntimeException e) {
            log.debug("Mevsimsel taban geçmişi okunamadı ({}#{}): {}", type, monitorId, e.getMessage());
            return History.EMPTY;
        }
    }

    /** İzlemenin tüm örneklerini siler (hedef / tanım değişti ya da taban çizgisi kapatıldı — eski ölçüler karışmasın). */
    public int deleteForMonitor(String type, long monitorId) {
        if (jdbc == null) return 0;
        try {
            return jdbc.update("DELETE FROM " + TABLE + " WHERE monitor_type = ? AND monitor_id = ?", type, monitorId);
        } catch (BadSqlGrammarException missing) {
            return 0;
        }
    }

    /** Budamanın tek silme ifadesinde en çok sileceği satır (uzun kilit / zaman aşımı olmasın). */
    static final int PRUNE_CHUNK = 5_000;
    /** Budama ifadelerinin sorgu zaman aşımı (sn) — yan iş iş parçacığında koşar; ilk budama büyük tabloda uzun sürebilir. */
    static final int PRUNE_QUERY_TIMEOUT_SECONDS = 120;

    /** Budama sonucu: silinen satır + işlenen izleme + bütçe / durdurma nedeniyle yarıda kaldı mı. */
    public record PruneResult(int deleted, int monitors, boolean partial) {}

    /** Mevsimsel izlemenin budamada korunacak geçmişi: periyot (gün / hafta) + okuma penceresi ({@code window}). */
    public record SeasonNeed(long periodMs, int window) {}

    /** Budama planı: izleme → mevsim ihtiyacı; {@code null} = mevsimsiz (yalnız satır sınırı). */
    @FunctionalInterface
    public interface SeasonNeeds {
        SeasonNeed need(String type, long monitorId);
    }

    /** Mevsimsel korumada okuma penceresinin güvenlik çarpanı (yoğunluk tahmini gürültüsü). */
    static final double SEASON_KEEP_FACTOR = 1.25;
    /** Mevsimsel korumanın ek payı (ms) — tolerans penceresinin üstüne. */
    static final long SEASON_KEEP_MARGIN_MS = 3_600_000L;

    /**
     * Mevsimsel izlemede budamanın KORUYACAĞI en eski an (saf): okuma en az bir periyot önceki her periyotta ±tolerans
     * penceresinden örnek toplar; son periyottaki satır sayısından pencere başına örnek ({@code perWindow}) tahmin edilir ve
     * {@code window × 1,25} örneğe yetecek {@code n} periyot (1 ≤ n ≤ window + 1) + tolerans + 1 sa korunur. Kısa aralıkta n = 1
     * (dünün / geçen haftanın aynı saati yeter), seyrek aralıkta n büyür (satır sayısı yine küçük kalır).
     */
    static long seasonalKeepFromMs(SeasonNeed need, long nowMs, long rowsLastPeriod) {
        long period = Math.max(1, need.periodMs());
        int window = Math.max(1, need.window());
        double perWindow = rowsLastPeriod * (2.0 * SEASON_TOLERANCE_MIN_MS) / period;
        long maxN = window + 1L;
        long n = perWindow <= 0 ? maxN : (long) Math.ceil(window * SEASON_KEEP_FACTOR / perWindow);
        n = Math.max(1, Math.min(maxN, n));
        return nowMs - n * period - SEASON_TOLERANCE_MIN_MS - SEASON_KEEP_MARGIN_MS;
    }

    /**
     * İzleme başına en yeni {@code keepPerMonitor} satırı tutar, gerisini siler — YALNIZ satır sınırı (mevsimsiz kural); günlük
     * budama işi ({@code BaselinePruneJob}) mevsime duyarlı {@link #prune(int, SeasonNeeds, long, java.util.function.BooleanSupplier)}
     * aşırı yüklemesini çağırır. Önce sınırı aşan izlemeler (tek gruplu sorgu), sonra izleme başına sınır satırı
     * (dizinden) ve en çok {@value #PRUNE_CHUNK} satırlık dilimlerle silme — tek dev ifade yerine (ilk budamada tablo büyük
     * olabilir; uzun kilit ve zaman aşımı olmasın). {@code stop} her dilimden önce sorulur (pod kapanıyor / bütçe doldu).
     */
    public PruneResult prune(int keepPerMonitor, java.util.function.BooleanSupplier stop) {
        return prune(keepPerMonitor, null, System.currentTimeMillis(), stop, PRUNE_CHUNK);
    }

    /** Mevsime duyarlı budama (günlük iş): bir satır yalnız en yeni {@code keepPerMonitor} satırın DIŞINDAYSA VE izlemenin
     *  mevsimsel ihtiyacından ({@link #seasonalKeepFromMs}) eskiyse silinir; {@code needs} null ya da izleme için null →
     *  yalnız satır sınırı. */
    public PruneResult prune(int keepPerMonitor, SeasonNeeds needs, long nowMs, java.util.function.BooleanSupplier stop) {
        return prune(keepPerMonitor, needs, nowMs, stop, PRUNE_CHUNK);
    }

    /** {@link #prune(int, java.util.function.BooleanSupplier)} dilim boyu verilerek (testler küçük dilimle çok dilimi sınar). */
    PruneResult prune(int keepPerMonitor, java.util.function.BooleanSupplier stop, int chunk) {
        return prune(keepPerMonitor, null, System.currentTimeMillis(), stop, chunk);
    }

    PruneResult prune(int keepPerMonitor, SeasonNeeds needs, long nowMs, java.util.function.BooleanSupplier stop, int chunk) {
        if (pruneJdbc == null) return new PruneResult(0, 0, false);
        int keep = Math.max(1, keepPerMonitor);
        int step = Math.max(1, chunk);
        JdbcTemplate long_ = pruneJdbc;
        List<Object[]> over;
        try {
            over = long_.query("SELECT monitor_type, monitor_id FROM " + TABLE
                            + " GROUP BY monitor_type, monitor_id HAVING COUNT(*) > ?",
                    (rs, n) -> new Object[] { rs.getString(1), rs.getLong(2) }, keep);
        } catch (BadSqlGrammarException missing) {
            return new PruneResult(0, 0, false);
        }
        int deleted = 0, monitors = 0;
        for (Object[] m : over) {
            if (stop != null && stop.getAsBoolean()) return new PruneResult(deleted, monitors, true);
            String type = (String) m[0];
            long id = (Long) m[1];
            // Silinecek EN YENİ satır = (keep+1). en yeni; okuma sırasıyla aynı (checked_ms DESC, id DESC)
            List<long[]> edge = long_.query("SELECT checked_ms, id FROM " + TABLE + " WHERE monitor_type = ? AND monitor_id = ? "
                            + "ORDER BY checked_ms DESC, id DESC LIMIT 1 OFFSET ?",
                    (rs, n) -> new long[] { rs.getLong(1), rs.getLong(2) }, type, id, keep);
            if (edge.isEmpty()) continue;
            long ms = edge.get(0)[0], rowId = edge.get(0)[1];
            // Mevsimsel izleme: satır sınırının dışında olsa da ihtiyaç duyulan süredeki satırlar KORUNUR (en az bir periyot
            // önceki aynı saat örnekleri — yalnız satır sayısına göre budama kısa aralıkta dünü / geçen haftayı silerdi).
            SeasonNeed need = needs == null ? null : needs.need(type, id);
            long keepFrom = Long.MAX_VALUE;
            if (need != null) {
                Long rows = long_.queryForObject("SELECT COUNT(*) FROM " + TABLE
                        + " WHERE monitor_type = ? AND monitor_id = ? AND checked_ms >= ?", Long.class,
                        type, id, nowMs - Math.max(1, need.periodMs()));
                keepFrom = seasonalKeepFromMs(need, nowMs, rows == null ? 0 : rows);
            }
            while (true) {
                if (stop != null && stop.getAsBoolean()) return new PruneResult(deleted, monitors, true);
                int n = long_.update("DELETE FROM " + TABLE + " WHERE id IN (SELECT id FROM " + TABLE
                        + " WHERE monitor_type = ? AND monitor_id = ? AND (checked_ms < ? OR (checked_ms = ? AND id <= ?)) "
                        + "AND checked_ms < ? ORDER BY checked_ms, id LIMIT ?)", type, id, ms, ms, rowId, keepFrom, step);
                deleted += n;
                if (n < step) break;
            }
            monitors++;
        }
        return new PruneResult(deleted, monitors, false);
    }

    /** {@link #prune(int, java.util.function.BooleanSupplier)} durdurmasız (testler / tanılama); hata → 0. */
    public int prune(int keepPerMonitor) {
        try {
            return prune(keepPerMonitor, null).deleted();
        } catch (RuntimeException e) {
            log.debug("Taban çizgisi örnekleri budanamadı: {}", e.getMessage());
            return 0;
        }
    }

    /** Test / tanılama: bir izlemenin örnek sayısı. */
    public int count(String type, long monitorId) {
        if (jdbc == null) return 0;
        try {
            Integer n = jdbc.queryForObject(
                    "SELECT COUNT(*) FROM " + TABLE + " WHERE monitor_type = ? AND monitor_id = ?",
                    Integer.class, type, monitorId);
            return n == null ? 0 : n;
        } catch (BadSqlGrammarException missing) {
            return 0;
        }
    }

    /** Non-seasonal okuma için yakın geçmiş satır ihtiyacı: pencerenin iki katı (ihlal dizisi + taban — Y1). */
    public static int recentNeed(BaselineParams params) {
        return Math.min(2 * BaselineParams.WINDOW_MAX, 2 * params.normalized().window());
    }
}
