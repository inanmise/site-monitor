package com.sitemonitor.service.certsweep;

import java.util.Collections;
import java.util.List;

/**
 * Parçalı sertifika taramasının DDL'i ve SQL'i (2026-10-29, çok pod Sürüm 3-4 paket A; tasarım R3-4 §4.1 / §4.2). Entity
 * YOK — iki ham tablo {@link CertSweepSchemaPatch} ile açılışta kurulur; yazımlar işlem DIŞINDA (otomatik commit, depo
 * {@code JdbcCertSweepStore} sınıf düzeyinde {@code NOT_SUPPORTED}) koşar: bir PostgreSQL hatası hiçbir çağıranın işlemini
 * bozamaz (25P02).
 *
 * <p><b>Tablolar (adlar KALICI — yayından sonra yeniden adlandırılmaz):</b>
 * <ul>
 *   <li>{@link #RUNS} — parçalı koşu başına bir satır (koordinatör yazar; RUNNING → DECIDING → DONE / FAILED / ABANDONED).
 *       Kapalı satırlar 7 günden eskiyse her parçalı tur başında budanır ({@link CertChunking#RUN_RETENTION_MS}).</li>
 *   <li>{@link #CHUNKS} — koşu başına parça satırları (≤ 500 + ikinci görüş): PENDING → CLAIMED (işçi) → DONE (sonuç JSON'u)
 *       ya da CANCELLED (koordinatör devraldı). Koşu kapanınca SİLİNİR; sahipsiz koşuların parçalarını bir sonraki koordinatör
 *       siler ({@code settleOrphans}).</li>
 * </ul>
 * Tüm zaman sütunları VERİTABANI-ÇAPALI saatle (3-3 {@code DbClock}) ms'dir. {@code results_json} asla günlüğe yazılmaz,
 * hiçbir API'den dönmez (denetleyici çıktısı: zincir, OCSP ayrıntısı, hata metni).
 *
 * <p><b>Taşınabilirlik:</b> tüm deyimler H2 (PostgreSQL kipi) ve PostgreSQL'de aynı metindir; YALNIZ sahiplenmenin tek ifadeli
 * biçimi ({@link #SQL_CLAIM_PG}: {@code WITH … FOR UPDATE OF k SKIP LOCKED … UPDATE … RETURNING}) PostgreSQL'e özgüdür — H2 /
 * bilinmeyen türde aday okuması + {@code attempts}'e bağlı CAS ({@link #SQL_CLAIM_CANDIDATES} + {@link #SQL_CLAIM_CAS}).
 */
public final class CertSweepSql {

    private CertSweepSql() {
    }

    /** Parçalı koşular — kalıcı ad. */
    public static final String RUNS = "cert_sweep_runs";
    /** Parçalar — kalıcı ad. */
    public static final String CHUNKS = "cert_sweep_chunks";
    /** İki tablo, kurulum sırasıyla. */
    public static final List<String> TABLES = List.of(RUNS, CHUNKS);

    /** Çok satırlı parça INSERT'ünün tek deyimdeki satır sayısı (§4.2: 200). */
    public static final int INSERT_ROWS = 200;
    /** {@code IN (…)} listelerinin tek deyimdeki üst sınırı. */
    public static final int IN_BATCH = 500;
    /** Taşınabilir sahiplenmede tek okumada en çok aday (CAS kaybedilirse sıradaki denenir). */
    public static final int CLAIM_CANDIDATES = 8;
    /** {@code claim_token} uzunluğu üst sınırı. */
    public static final int TOKEN_MAX = 40;
    /** Örnek kimliği sütunlarının uzunluğu ({@code coordinator}, {@code claimed_by}, {@code worker}, {@code avoid_worker}). */
    public static final int INSTANCE_MAX = 200;
    /** Öksüz koşu okumasının tavanı (normalde 0–1 açık koşu olur). */
    public static final int OPEN_RUNS_MAX = 100;

    // ── DDL ─────────────────────────────────────────────────────────────────────────────────────────────────────────

    /** Koşu tablosu (§4.1). */
    public static final String DDL_RUNS = "CREATE TABLE IF NOT EXISTS " + RUNS + " ("
            + "run_id VARCHAR(40) PRIMARY KEY, "
            + "kind VARCHAR(10) NOT NULL, "
            + "coordinator VARCHAR(200) NOT NULL, "
            + "state VARCHAR(12) NOT NULL, "
            + "evict_caches BOOLEAN NOT NULL, "
            + "domains_total INT NOT NULL, "
            + "chunks_total INT NOT NULL, "
            + "chunk_size INT NOT NULL, "
            + "created_ms BIGINT NOT NULL, "
            + "heartbeat_ms BIGINT NOT NULL, "
            + "finished_ms BIGINT, "
            + "outcome VARCHAR(20), "
            + "takeovers INT, "
            + "reclaims INT, "
            + "second_opinions INT, "
            + "workers_json VARCHAR(4000), "
            + "second_opinion_ok INT, "
            + "second_opinion_failed INT)";

    /** Koşu durumu + yaş dizini (öksüz okuması, budama). */
    public static final String DDL_RUNS_STATE_INDEX = "CREATE INDEX IF NOT EXISTS idx_csr_state ON " + RUNS + "(state, created_ms)";

    /** Parça tablosu (§4.1). */
    public static final String DDL_CHUNKS = "CREATE TABLE IF NOT EXISTS " + CHUNKS + " ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "run_id VARCHAR(40) NOT NULL, "
            + "chunk_no INT NOT NULL, "
            + "state VARCHAR(10) NOT NULL, "
            + "domains_json TEXT NOT NULL, "
            + "domain_count INT NOT NULL, "
            + "avoid_worker VARCHAR(200), "
            + "attempts INT NOT NULL, "
            + "created_ms BIGINT NOT NULL, "
            + "claimed_by VARCHAR(200), "
            + "claim_token VARCHAR(40), "
            + "claimed_ms BIGINT, "
            + "lease_until_ms BIGINT, "
            + "finished_ms BIGINT, "
            + "worker VARCHAR(200), "
            + "results_json TEXT, "
            + "checked INT, "
            + "network_errors INT, "
            + "errors INT, "
            + "warnings INT)";

    /** Koşu × parça numarası tekil (aynı turda numara iki kez yazılamaz). */
    public static final String DDL_CHUNKS_RUN_UNIQUE =
            "CREATE UNIQUE INDEX IF NOT EXISTS ux_csc_run_chunk ON " + CHUNKS + "(run_id, chunk_no)";
    /** Durum + sıra dizini (sahiplenme adayları {@code ORDER BY id}). */
    public static final String DDL_CHUNKS_STATE_INDEX = "CREATE INDEX IF NOT EXISTS idx_csc_state ON " + CHUNKS + "(state, id)";

    /**
     * Yalnız PostgreSQL: sıcak, küçük parça tablosunda sabit eşikli otomatik süpürme (ölü satır oranı değil, 500 ölü satır) —
     * her tur ≈ 60 parça yazar / günceller / siler. {@code SchemaDdlGuard} {@code SET (reloptions)} biçimini tanır.
     */
    public static final String RELOPTIONS_PG = "ALTER TABLE " + CHUNKS
            + " SET (autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 500)";

    // ── Koşu (koordinatör) ──────────────────────────────────────────────────────────────────────────────────────────

    /** Koşu sütunları (okuma; {@code CertSweepStatus.Run} sırası). */
    public static final String RUN_COLS = "run_id, kind, coordinator, state, evict_caches, domains_total, chunks_total, "
            + "chunk_size, created_ms, heartbeat_ms, finished_ms, outcome, takeovers, reclaims, second_opinions, workers_json, "
            + "second_opinion_ok, second_opinion_failed";

    /** Açık koşular (öksüz kapatma öncesi okuması). Parametre: tavan. */
    public static final String SQL_OPEN_RUNS = "SELECT " + RUN_COLS + " FROM " + RUNS
            + " WHERE state IN ('RUNNING','DECIDING') ORDER BY created_ms LIMIT ?";

    /** Öksüz kapatma (koşu başına koşullu). Parametreler: bitiş, koşu. */
    public static final String SQL_SETTLE_ONE = "UPDATE " + RUNS + " SET state = 'ABANDONED', outcome = 'ORPHANED', "
            + "finished_ms = ? WHERE run_id = ? AND state IN ('RUNNING','DECIDING')";

    /** Açık koşusu olmayan TÜM parçalar (kapalı koşuların ve koşu satırı hiç yazılmamış yarım kurulumların). */
    public static final String SQL_DELETE_DEAD_CHUNKS = "DELETE FROM " + CHUNKS + " WHERE NOT EXISTS (SELECT 1 FROM " + RUNS
            + " r WHERE r.run_id = " + CHUNKS + ".run_id AND r.state IN ('RUNNING','DECIDING'))";

    /** Budama adayları: eşikten eski KAPALI koşular. Parametreler: eşik, tavan. */
    public static final String SQL_PRUNE_CANDIDATES = "SELECT run_id FROM " + RUNS
            + " WHERE created_ms < ? AND state NOT IN ('RUNNING','DECIDING') ORDER BY created_ms LIMIT ?";

    /** Budama (koşullu). Parametreler: eşik, koşular… */
    public static String pruneRuns(int ids) {
        return "DELETE FROM " + RUNS + " WHERE created_ms < ? AND state NOT IN ('RUNNING','DECIDING') AND run_id IN ("
                + placeholders(ids) + ")";
    }

    /** Kurulum öncesi çakışma denetimi: bu kimlikte koşu ya da parça var mı. Parametreler: koşu, koşu. */
    public static final String SQL_RUN_ID_TAKEN = "SELECT (SELECT COUNT(*) FROM " + RUNS + " WHERE run_id = ?) + (SELECT COUNT(*) FROM "
            + CHUNKS + " WHERE run_id = ?)";

    /** Koşu satırı (EN SON yazılır — parçalar ancak koşu RUNNING iken sahiplenilebilir). */
    public static final String SQL_INSERT_RUN = "INSERT INTO " + RUNS + " (run_id, kind, coordinator, state, evict_caches, "
            + "domains_total, chunks_total, chunk_size, created_ms, heartbeat_ms) VALUES (?, ?, ?, 'RUNNING', ?, ?, ?, ?, ?, ?)";

    /**
     * Çok satırlı parça INSERT'ü ({@code rows} satır; satır başına 6 parametre: koşu, numara, alan adları JSON'u, alan adı
     * sayısı, kaçınılan işçi, oluşturma).
     */
    public static String insertChunks(int rows) {
        StringBuilder sb = new StringBuilder("INSERT INTO ").append(CHUNKS)
                .append(" (run_id, chunk_no, state, domains_json, domain_count, avoid_worker, attempts, created_ms) VALUES ");
        for (int i = 0; i < rows; i++) {
            if (i > 0) sb.append(", ");
            sb.append("(?, ?, 'PENDING', ?, ?, ?, 0, ?)");
        }
        return sb.toString();
    }

    /** Yarım kurulumun temizliği: bu koşunun parçaları. Parametre: koşu. */
    public static final String SQL_DELETE_RUN_CHUNKS = "DELETE FROM " + CHUNKS + " WHERE run_id = ?";

    /** Nabız. Parametreler: an, koşu. */
    public static final String SQL_HEARTBEAT = "UPDATE " + RUNS + " SET heartbeat_ms = ? WHERE run_id = ? AND state = 'RUNNING'";

    /** Parça durum sütunları ({@link ChunkState} sırası; JSON YOK). */
    public static final String CHUNK_STATE_COLS = "id, chunk_no, state, attempts, domain_count, created_ms, claimed_by, "
            + "claimed_ms, lease_until_ms, worker, finished_ms, checked, network_errors, avoid_worker";

    /** Koşunun parça durumları. Parametreler: koşu, tavan. */
    public static final String SQL_CHUNK_STATES = "SELECT " + CHUNK_STATE_COLS + " FROM " + CHUNKS
            + " WHERE run_id = ? ORDER BY chunk_no LIMIT ?";

    /** DONE parçaların sonuç JSON'u. Parametreler: koşu, kimlikler… */
    public static String readResults(int ids) {
        return "SELECT id, results_json FROM " + CHUNKS + " WHERE run_id = ? AND state = 'DONE' AND id IN (" + placeholders(ids)
                + ")";
    }

    /** Devralma (koşullu iptal). Parametreler: parça, koşu. */
    public static final String SQL_CANCEL = "UPDATE " + CHUNKS + " SET state = 'CANCELLED', lease_until_ms = NULL "
            + "WHERE id = ? AND run_id = ? AND state IN ('PENDING','CLAIMED')";

    /**
     * Karar aşaması. Parametreler: işçiler JSON'u, devralma, yeniden sahiplenme, ikinci görüş, ikinci görüşte başka pod'da başarılı,
     * yine hatalı (inceleme L-4; null olabilir), koşu.
     */
    public static final String SQL_MARK_DECIDING = "UPDATE " + RUNS + " SET state = 'DECIDING', workers_json = ?, takeovers = ?, "
            + "reclaims = ?, second_opinions = ?, second_opinion_ok = ?, second_opinion_failed = ? WHERE run_id = ? "
            + "AND state = 'RUNNING'";

    /** Kapanış. Parametreler: durum, sonuç, bitiş, koşu. */
    public static final String SQL_FINISH = "UPDATE " + RUNS + " SET state = ?, outcome = ?, finished_ms = ? "
            + "WHERE run_id = ? AND state IN ('RUNNING','DECIDING')";

    // ── İşçi ────────────────────────────────────────────────────────────────────────────────────────────────────────

    /**
     * Koordinatörü YAŞAYAN, RUNNING koşunun parçası mı ({@code k} takma adıyla) + liderin bekletme kapısı. Bekletme kapısı
     * ({@code k.created_ms < ?}, FX-WORKER 2026-10-29: SW-M1 / CR-L1 / CR-H-1 b) YALNIZ BAŞKA bir pod'un koordine ettiği
     * koşunun İLK GÖRÜŞ parçalarına uygulanır: sahiplenen pod'un KENDİ koşusunun parçaları ({@code r.coordinator = sahip}) ve
     * ikinci görüş parçaları ({@code k.avoid_worker IS NOT NULL}) eşikten muaftır (lider onları beklemeden alır). Eşik
     * {@link Long#MAX_VALUE} = herkes, {@link Long#MIN_VALUE} = YALNIZ muaf parçalar. Parametreler: nabız eşiği, oluşturma
     * eşiği, sahip.
     */
    private static final String RUN_ALIVE_K = "EXISTS (SELECT 1 FROM " + RUNS + " r WHERE r.run_id = k.run_id "
            + "AND r.state = 'RUNNING' AND r.heartbeat_ms >= ? "
            + "AND (k.created_ms < ? OR k.avoid_worker IS NOT NULL OR r.coordinator = ?))";

    /**
     * Sahiplenme aday koşulu ({@code k} takma adı): PENDING ya da kirası dolmuş CLAIMED, deneme tavanı altı, kaçınılan işçi bu
     * değil, koşusu RUNNING ve koordinatörün nabzı taze, oluşturma eşiği öncesi (yalnız başka koordinatörün ilk görüş
     * parçaları için — {@link #RUN_ALIVE_K}). Parametreler: şimdi, tavan, sahip (kaçınılan), nabız eşiği, oluşturma eşiği,
     * sahip (koordinatör).
     */
    static final String CANDIDATE_WHERE = "(k.state = 'PENDING' OR (k.state = 'CLAIMED' AND k.lease_until_ms < ?)) "
            + "AND k.attempts < ? AND (k.avoid_worker IS NULL OR k.avoid_worker <> ?) AND " + RUN_ALIVE_K;

    /**
     * Sahiplenme sonucu sütunları (iki yol aynı etiketlerle okur), {@code alias} takma adlı parça satırından. FX-WORKER
     * (2026-10-29): parçanın {@code created_ms}'i, {@code avoid_worker}'ı ve koşusunun {@code coordinator}'ı da döner — işçi
     * kendi koşusunu / ikinci görüşü / bekleme yaşını bilir (alt sorgu kilit almaz).
     */
    static String claimedCols(String alias) {
        String a = alias + ".";
        return a + "id AS id, " + a + "run_id AS run_id, " + a + "chunk_no AS chunk_no, " + a + "domains_json AS domains_json, "
                + a + "attempts AS attempts, " + a + "claim_token AS claim_token, " + a + "claimed_ms AS claimed_ms, "
                + a + "lease_until_ms AS lease_until_ms, " + a + "created_ms AS created_ms, " + a + "avoid_worker AS avoid_worker, "
                + "(SELECT r.coordinator FROM " + RUNS + " r WHERE r.run_id = " + a + "run_id) AS coordinator";
    }

    /** Sahiplenme sonucu sütunları ({@code k} takma adıyla; taşınabilir yolun 3. adımı). */
    public static final String CLAIMED_COLS = claimedCols("k");

    /**
     * PostgreSQL tek ifadeli sahiplenme (3-3 QW-L8 CTE biçimi): aday CTE'de BİR KEZ seçilip kilitlenir ({@code FOR UPDATE OF k
     * SKIP LOCKED}, {@code LIMIT 1}), dış {@code UPDATE … FROM c} yalnız onu günceller — iki işçi aynı parçayı alamaz.
     * Parametreler: [aday koşulu], sahip, belirteç, şimdi, kira bitişi.
     */
    public static final String SQL_CLAIM_PG = "WITH c AS (SELECT k.id FROM " + CHUNKS + " k WHERE " + CANDIDATE_WHERE
            + " ORDER BY k.id LIMIT 1 FOR UPDATE OF k SKIP LOCKED) "
            + "UPDATE " + CHUNKS + " j SET state = 'CLAIMED', claimed_by = ?, claim_token = ?, claimed_ms = ?, "
            + "lease_until_ms = ?, attempts = j.attempts + 1 FROM c WHERE j.id = c.id RETURNING " + claimedCols("j");

    /**
     * Taşınabilir sahiplenme 1. adım: adaylar (kilitsiz). Parametreler: [aday koşulu], tavan. (Bekletme kapısının girdileri —
     * {@code created_ms}, {@code avoid_worker}, koşunun {@code coordinator}'ı — yazımdan sonra değişmez; CAS onları yeniden
     * denetlemez.)
     */
    public static final String SQL_CLAIM_CANDIDATES = "SELECT k.id, k.attempts FROM " + CHUNKS + " k WHERE " + CANDIDATE_WHERE
            + " ORDER BY k.id LIMIT ?";

    /**
     * Taşınabilir sahiplenme 2. adım: CAS (okunan deneme sayısı + hâlâ sahiplenilebilir + koşu hâlâ RUNNING ve canlı).
     * Parametreler: sahip, belirteç, şimdi, kira bitişi, id, okunan deneme, şimdi, nabız eşiği.
     */
    public static final String SQL_CLAIM_CAS = "UPDATE " + CHUNKS + " SET state = 'CLAIMED', claimed_by = ?, claim_token = ?, "
            + "claimed_ms = ?, lease_until_ms = ?, attempts = attempts + 1 WHERE id = ? AND attempts = ? "
            + "AND (state = 'PENDING' OR (state = 'CLAIMED' AND lease_until_ms < ?)) AND EXISTS (SELECT 1 FROM " + RUNS
            + " r WHERE r.run_id = " + CHUNKS + ".run_id AND r.state = 'RUNNING' AND r.heartbeat_ms >= ?)";

    /** Taşınabilir sahiplenme 3. adım: kazanılan satır. Parametreler: id, belirteç. */
    public static final String SQL_CLAIMED_ROW = "SELECT " + CLAIMED_COLS + " FROM " + CHUNKS + " k WHERE k.id = ? AND k.claim_token = ?";

    /** Kira yenileme (bu pod'un tuttukları, tek deyim). Parametreler: kira bitişi, sahip, kimlikler… */
    public static String renew(int ids) {
        return "UPDATE " + CHUNKS + " SET lease_until_ms = ? WHERE claimed_by = ? AND state = 'CLAIMED' AND id IN ("
                + placeholders(ids) + ")";
    }

    /**
     * Tamamlama: yalnız hâlâ BU sahiplenmenin belirteciyle CLAIMED ve koşusu RUNNING. Parametreler: sonuçlar, ölçülen, ağ
     * hatası, hata, uyarı, bitiş, işçi, id, belirteç.
     */
    public static final String SQL_COMPLETE = "UPDATE " + CHUNKS + " SET state = 'DONE', results_json = ?, checked = ?, "
            + "network_errors = ?, errors = ?, warnings = ?, finished_ms = ?, worker = ?, lease_until_ms = NULL "
            + "WHERE id = ? AND state = 'CLAIMED' AND claim_token = ? AND EXISTS (SELECT 1 FROM " + RUNS
            + " r WHERE r.run_id = " + CHUNKS + ".run_id AND r.state = 'RUNNING')";

    /** Kapanışta bırakma: PENDING'e (deneme bir geri). Parametreler: sahip, kimlikler… */
    public static String release(int ids) {
        return "UPDATE " + CHUNKS + " SET state = 'PENDING', claimed_by = NULL, claim_token = NULL, claimed_ms = NULL, "
                + "lease_until_ms = NULL, attempts = CASE WHEN attempts > 0 THEN attempts - 1 ELSE 0 END "
                + "WHERE claimed_by = ? AND state = 'CLAIMED' AND id IN (" + placeholders(ids) + ")";
    }

    // ── Durum (Sistem Sağlığı / Küme kartı) ─────────────────────────────────────────────────────────────────────────

    /** En yeni koşular. Parametre: tavan. */
    public static final String SQL_LAST_RUNS = "SELECT " + RUN_COLS + " FROM " + RUNS + " ORDER BY created_ms DESC, run_id DESC LIMIT ?";

    /**
     * Açık koşunun gruplu parça sayıları (türetilmiş tablo — H2 {@code GROUP BY 1, 2}'yi reddeder). Ağ hatası yalnız DONE
     * parçalarınki. Parametre: koşu.
     */
    public static final String SQL_CHUNK_GROUPS = "SELECT state, w, COUNT(*) AS n, SUM(domain_count) AS d, SUM(ne) AS ne, "
            + "MIN(created_ms) AS mc FROM (SELECT state, COALESCE(worker, claimed_by) AS w, domain_count, "
            + "CASE WHEN state = 'DONE' THEN COALESCE(network_errors, 0) ELSE 0 END AS ne, created_ms FROM " + CHUNKS
            + " WHERE run_id = ?) x GROUP BY state, w";

    /** {@code n} adet "?" virgülle. */
    static String placeholders(int n) {
        return String.join(", ", Collections.nCopies(Math.max(1, n), "?"));
    }
}
