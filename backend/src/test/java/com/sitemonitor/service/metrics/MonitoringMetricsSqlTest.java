package com.sitemonitor.service.metrics;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Aktarıcının yerel SQL'i (2026-10-18) H2 (PostgreSQL kipi) üzerinde gerçekten koşar: türetilmiş tablo + CASE sınıflaması
 * (H2 {@code GROUP BY 1, 2}'yi reddeder — gruplama sütun adıyla), push sayımları ve kilit okuması. PostgreSQL'de aynı
 * ifadeler {@code ON CONFLICT} gibi lehçe özelliği taşımaz.
 */
class MonitoringMetricsSqlTest {

    JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:metrics-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE notification_logs (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, alert_event_id BIGINT NOT NULL, "
                + "sent_at VARCHAR(255), email_status VARCHAR(255), webhook_status VARCHAR(255), \"trigger\" VARCHAR(255))");
        jdbc.execute("CREATE TABLE user_push_deliveries (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status VARCHAR(40) NOT NULL, "
                + "created_at VARCHAR(255) NOT NULL, next_attempt_at VARCHAR(255))");
        jdbc.execute("CREATE TABLE scheduler_lock (name VARCHAR(200) PRIMARY KEY, locked_by VARCHAR(200) NOT NULL, locked_until VARCHAR(40) NOT NULL)");
    }

    @Test
    @DisplayName("bildirim sorgusu: e-posta / webhook durumu SQL'de sınıflanır, 24 sa penceresi dışı sayılmaz")
    void notificationQueries() {
        jdbc.update("INSERT INTO notification_logs(alert_event_id, sent_at, email_status, webhook_status, \"trigger\") VALUES "
                + "(1,'2026-10-18T07:00:00','SENT',NULL,'INITIAL'),(1,'2026-10-18T07:10:00','FAILED: 550','SENT','INITIAL'),"
                + "(2,'2026-10-18T07:20:00','SKIPPED: fırtına #3',NULL,'STORM'),(3,'2026-10-16T07:00:00','SENT',NULL,'INITIAL')");
        List<Object[]> email = jdbc.query(MonitoringMetricsExporter.SQL_NOTIFY_EMAIL,
                (rs, i) -> new Object[]{rs.getString(1), rs.getString(2), rs.getString(3), rs.getLong(4)}, "2026-10-17T08:00:00");
        assertThat(email).extracting(r -> r[1] + "|" + r[2] + "|" + r[3])
                .containsExactlyInAnyOrder("INITIAL|SENT|1", "INITIAL|FAILED|1", "STORM|SKIPPED|1");
        assertThat(email).allMatch(r -> "email".equals(r[0]));
        List<Object[]> webhook = jdbc.query(MonitoringMetricsExporter.SQL_NOTIFY_WEBHOOK,
                (rs, i) -> new Object[]{rs.getString(1), rs.getString(2), rs.getString(3), rs.getLong(4)}, "2026-10-17T08:00:00");
        assertThat(webhook).extracting(r -> r[1] + "|" + r[2] + "|" + r[3])
                .containsExactlyInAnyOrder("INITIAL|NONE|1", "INITIAL|SENT|1", "STORM|NONE|1");
        MonitoringMetricsModel.Families f = new MonitoringMetricsModel.Families();
        MonitoringMetricsModel.notifications(f, webhook);
        assertThat(f.get(MonitoringMetricNames.NOTIFICATIONS)).hasSize(1);
    }

    @Test
    @DisplayName("push sorguları: 24 sa durum dağılımı, bekleyen ve takılı (watchdog tanımıyla aynı) sayılar")
    void pushQueries() {
        jdbc.update("INSERT INTO user_push_deliveries(status, created_at, next_attempt_at) VALUES "
                + "('SENT','2026-10-18T07:00:00',NULL),('PENDING','2026-10-18T07:00:00',NULL),"
                + "('PENDING','2026-10-18T07:58:00',NULL),('SKIPPED_STORM','2026-10-18T07:30:00',NULL)");
        List<Object[]> rows = jdbc.query(MonitoringMetricsExporter.SQL_PUSH_24H, (rs, i) -> new Object[]{rs.getString(1), rs.getLong(2)},
                "2026-10-17T08:00:00");
        assertThat(rows).hasSize(3);
        assertThat(jdbc.queryForObject(MonitoringMetricsExporter.SQL_PUSH_PENDING, Long.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject(MonitoringMetricsExporter.SQL_PUSH_STUCK, Long.class, "2026-10-18T07:45:00", "2026-10-18T07:50:00"))
                .isEqualTo(1);
    }

    @Test
    @DisplayName("kilit sorgusu: ad + bitiş okunur")
    void lockQuery() {
        jdbc.update("INSERT INTO scheduler_lock(name, locked_by, locked_until) VALUES ('cert-check','pod-a','2026-10-18T09:00:00')");
        List<Object[]> rows = jdbc.query(MonitoringMetricsExporter.SQL_LOCKS, (rs, i) -> new Object[]{rs.getString(1), rs.getString(2)});
        assertThat(rows).hasSize(1);
        assertThat(rows.get(0)[0]).isEqualTo("cert-check");
    }
}
