package com.sitemonitor.service.metrics;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * k6r D3 (2026-10-31): sentetik koşum aileleri — {@code sitemonitor_scripted_runs_24h{status}} ve
 * {@code sitemonitor_scripted_k6_versions_24h{version}} TEK gruplu sorgudan (H2, PostgreSQL kipi; yalnız zamanlanmış koşumlar,
 * 24 sa penceresi) ve modelin sınıflaması (beş sonuç sıfırlar dahil, sürümsüz = unknown, sürüm tavanı).
 */
class ScriptedRunMetricsTest {

    private static JdbcTemplate h2() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:k6runs-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH");
        JdbcTemplate jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE scripted_checks (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, monitor_id BIGINT NOT NULL, "
                + "ok BOOLEAN NOT NULL, status VARCHAR(255) NOT NULL, k6_version VARCHAR(20), manual BOOLEAN, checked_at VARCHAR(255))");
        return jdbc;
    }

    private static Map<String, Double> byLabel(MonitoringMetricsModel.Families f, String name, String label) {
        Map<String, Double> out = new LinkedHashMap<>();
        for (MonitoringMetricsModel.Row r : f.get(name)) out.put(r.labels().get(label), r.value());
        return out;
    }

    @Test
    @DisplayName("SQL: son 24 sa zamanlanmış koşumlar (manual NULL / false) sonuç × sürüm; elle koşum ve pencere dışı sayılmaz")
    void sqlCountsScheduledRunsInWindow() {
        JdbcTemplate jdbc = h2();
        jdbc.update("INSERT INTO scripted_checks(monitor_id, ok, status, k6_version, manual, checked_at) VALUES "
                + "(1, TRUE, 'PASS', 'v2.3.0', NULL, '2026-11-09T07:00:00'),"
                + "(1, TRUE, 'PASS', 'v2.3.0', FALSE, '2026-11-09T07:05:00'),"
                + "(2, FALSE, 'FAIL', 'v2.3.0', FALSE, '2026-11-09T07:10:00'),"
                + "(3, FALSE, 'TIMEOUT', NULL, NULL, '2026-11-09T06:00:00'),"
                + "(4, TRUE, 'PASS', 'v2.3.0', TRUE, '2026-11-09T07:20:00'),"           // elle → sayılmaz
                + "(5, FALSE, 'ERROR', 'v0.49.0', NULL, '2026-11-07T07:00:00')");      // 24 sa dışı → sayılmaz
        List<Object[]> rows = jdbc.query(MonitoringMetricsExporter.SQL_SCRIPTED_RUNS,
                (rs, i) -> new Object[]{rs.getString(1), rs.getString(2), rs.getLong(3)}, "2026-11-08T08:00:00");
        MonitoringMetricsModel.Families f = new MonitoringMetricsModel.Families();
        MonitoringMetricsModel.scriptedRuns(f, rows);
        assertThat(byLabel(f, MonitoringMetricNames.SCRIPTED_RUNS, "status"))
                .containsExactly(Map.entry("PASS", 2.0), Map.entry("FAIL", 1.0), Map.entry("ERROR", 0.0),
                        Map.entry("TIMEOUT", 1.0), Map.entry("NO_CHECKS", 0.0));
        assertThat(byLabel(f, MonitoringMetricNames.SCRIPTED_K6_VERSIONS, "version"))
                .containsExactly(Map.entry("v2.3.0", 3.0), Map.entry("unknown", 1.0));
    }

    @Test
    @DisplayName("model: hiç koşum yok → beş sonuç SIFIR yazılır (okunabilir kaynak), sürüm ailesi boş (veri yok ≠ 0)")
    void emptyRowsWriteZerosForResults() {
        MonitoringMetricsModel.Families f = new MonitoringMetricsModel.Families();
        MonitoringMetricsModel.scriptedRuns(f, List.of());
        assertThat(byLabel(f, MonitoringMetricNames.SCRIPTED_RUNS, "status")).hasSize(5).allSatisfy((k, v) -> assertThat(v).isZero());
        assertThat(f.get(MonitoringMetricNames.SCRIPTED_K6_VERSIONS)).isEmpty();
    }

    @Test
    @DisplayName("model: tanınmayan durum OTHER; boş sürüm unknown; 20'den fazla sürüm → kalanı 'other'")
    void unknownStatusAndVersionCap() {
        List<Object[]> rows = new ArrayList<>();
        rows.add(new Object[]{"SKIPPED", "", 2L});
        rows.add(new Object[]{null, null, 1L});
        for (int i = 0; i < 25; i++) rows.add(new Object[]{"pass", "v1." + i + ".0", (long) (100 - i)});
        MonitoringMetricsModel.Families f = new MonitoringMetricsModel.Families();
        MonitoringMetricsModel.scriptedRuns(f, rows);
        Map<String, Double> st = byLabel(f, MonitoringMetricNames.SCRIPTED_RUNS, "status");
        assertThat(st.get("OTHER")).isEqualTo(3.0);
        assertThat(st.get("PASS")).isGreaterThan(0);
        Map<String, Double> v = byLabel(f, MonitoringMetricNames.SCRIPTED_K6_VERSIONS, "version");
        assertThat(v).hasSize(MonitoringMetricsModel.MAX_K6_VERSIONS + 1).containsKey("other").containsKey("v1.0.0");
        assertThat(v.keySet()).doesNotContain("v1.24.0");
        double total = v.values().stream().mapToDouble(Double::doubleValue).sum();
        double runs = st.values().stream().mapToDouble(Double::doubleValue).sum();
        assertThat(total).isEqualTo(runs);   // iki aile aynı koşumları sayar
    }
}
