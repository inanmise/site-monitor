package com.sitemonitor.service.metrics;

import com.sitemonitor.service.AppSettingsService;
import com.sitemonitor.service.SchedulerService;
import com.sitemonitor.service.health.ClusterHealthStore;
import com.sitemonitor.service.schedule.PodLiveness;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.context.ApplicationContext;
import org.springframework.context.event.ContextClosedEvent;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.Optional;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.anyBoolean;
import static org.mockito.ArgumentMatchers.anyInt;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * Çok pod R3-1 inceleme M1 (2026-10-23, FX-OBS): iki aktarıcı AYNI H2 {@code cluster_observations} satırını (gerçek
 * {@link ClusterHealthStore}) ve ayrı örnek kimliklerini kullanır. Kurum ailelerini yayan takipçi kapanınca tarama lideri
 * (yalnız POD aileleri yayıyordu) satırın eskimesini (150 sn) beklemeden ~10 sn'lik yeniden denetimde yaymaya döner — iş
 * panelleri 1,5–3,5 dk boş kalmaz. Liderin döngüsü GERÇEK yürütücüyle koşar (denetim aralığı test için kısaltılmış).
 */
class MonitoringMetricsExporterMultiPodTest {

    static final AtomicInteger SEQ = new AtomicInteger();
    static final Instant T0 = Instant.parse("2026-10-23T09:00:00Z");
    static final String POD_A = "sitemonitor-a-0000000a";
    static final String POD_B = "sitemonitor-b-0000000b";
    static final String HEARTBEAT_DDL = "CREATE TABLE IF NOT EXISTS system_heartbeat ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recorded_at TIMESTAMP NOT NULL, "
            + "instance_id VARCHAR(120), shutdown_marker BOOLEAN)";

    JdbcTemplate jdbc;
    ClusterHealthStore store;
    final AtomicReference<Instant> clock = new AtomicReference<>(T0);
    MonitoringMetricsExporter leader;
    MonitoringMetricsExporter follower;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:exportermultipod" + SEQ.incrementAndGet()
                + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE"));
        jdbc.execute(ClusterHealthStore.OBS_DDL);
        jdbc.execute(HEARTBEAT_DDL);
        store = new ClusterHealthStore(jdbc);
        leader = exporter(POD_A, true);
        follower = exporter(POD_B, false);
        // İki pod da canlı (heartbeat; kapanış işareti yok)
        beat(POD_A);
        beat(POD_B);
        leader.setLivenessForTest(new PodLiveness(jdbc, POD_A, () -> clock.get().toEpochMilli()));
    }

    @AfterEach
    void tearDown() {
        leader.stop();
        follower.stop();
        jdbc.execute("SHUTDOWN");
    }

    MonitoringMetricsExporter exporter(String id, boolean isLeader) {
        AppSettingsService settings = mock(AppSettingsService.class);
        when(settings.getBoolean(anyString(), anyBoolean())).thenAnswer(i -> i.getArgument(1));
        when(settings.getInt(anyString(), anyInt())).thenAnswer(i -> i.getArgument(1));
        MonitoringMetricsExporter e = new MonitoringMetricsExporter(new SimpleMeterRegistry(), settings);
        e.setInstanceIdForTest(id);
        e.setClock(clock::get);
        e.setClusterHealth(store);
        SchedulerService scheduler = mock(SchedulerService.class);
        when(scheduler.sweepLeaderHint()).thenReturn(isLeader);
        e.setScheduler(scheduler);
        return e;
    }

    void beat(String instance) {
        jdbc.update("INSERT INTO system_heartbeat(recorded_at, instance_id, shutdown_marker) VALUES (?, ?, ?)",
                LocalDateTime.ofInstant(clock.get(), ZoneOffset.UTC), instance, null);
    }

    Optional<ClusterHealthStore.Observation> row() {
        return store.read(ClusterHealthStore.OBS_METRICS_ORG);
    }

    static void awaitTrue(java.util.function.BooleanSupplier cond, long timeoutMs, String what) throws InterruptedException {
        long until = System.nanoTime() + timeoutMs * 1_000_000L;
        while (System.nanoTime() < until) {
            if (cond.getAsBoolean()) return;
            Thread.sleep(20);
        }
        assertThat(cond.getAsBoolean()).as(what).isTrue();
    }

    @Test
    @DisplayName("takipçi yayar ve gözlem yazar → lider yalnız POD aileleri → takipçi kapanır (kapanış işareti) → lider ≤ 15 sn içinde "
            + "kurum ailelerini yayar; kapanan takipçi bir daha gözlem yazmaz")
    void followerCloses_leaderResumesWithinSeconds() throws Exception {
        // 1) Takipçi kurum ailelerini eksiksiz yayar → gözlem (kendi kimliği)
        assertThat(follower.refresh().orgFamilies()).isTrue();
        assertThat(row()).get().extracting(ClusterHealthStore.Observation::instanceId).isEqualTo(POD_B);

        // 2) Lider gerçek döngüyle başlar: taze yabancı gözlem + yayımlayan canlı → yalnız POD aileleri
        leader.initialDelayMs = 0;
        leader.recheckMs = 100;
        leader.start();
        awaitTrue(() -> leader.lastStatus() != null, 10_000, "liderin ilk turu");
        assertThat(leader.lastStatus().orgFamilies()).as("takipçi yayıyor — lider yalnız POD aileleri").isFalse();
        Thread.sleep(400);   // birkaç yeniden denetim: takipçi canlı ve gözlem taze → lider beklemede kalır
        assertThat(leader.lastStatus().orgFamilies()).isFalse();

        // 3) Takipçi kapanır: kapanış işareti kendi iş parçacığında (dinleyici beklemez)
        follower.initialDelayMs = 3_600_000L;   // döngüsü bu testte koşmasın (yürütücü yalnız kapanış işareti için)
        follower.start();
        long t0 = System.nanoTime();
        follower.onContextClosed(new ContextClosedEvent(mock(ApplicationContext.class)));
        awaitTrue(() -> row().map(o -> o.payload() != null && o.payload().contains("\"stopping\":true")).orElse(false),
                10_000, "kapanış işareti yazıldı");

        // 4) Lider ≤ 15 sn (üretimde ≤ 10 sn denetim + bir tur; burada denetim 100 ms) içinde kurum ailelerini yayar
        awaitTrue(() -> leader.lastStatus().orgFamilies(), 15_000, "lider kurum ailelerine döndü");
        long elapsedMs = (System.nanoTime() - t0) / 1_000_000L;
        assertThat(elapsedMs).isLessThanOrEqualTo(15_000L);

        // 5) Kapanan takipçi yine tur koşar (pod ölene dek yayar) ama gözlem YAZMAZ — kapanış işareti yerinde kalır
        clock.set(T0.plusSeconds(5));
        assertThat(follower.refresh().orgFamilies()).isTrue();
        assertThat(row()).get().satisfies(o -> assertThat(o.payload()).contains("\"stopping\":true"));
        // Lider gözlem yazmaz (yalnız takipçi yazar)
        assertThat(row()).get().extracting(ClusterHealthStore.Observation::instanceId).isEqualTo(POD_B);
    }

    @Test
    @DisplayName("liderliği bırakan (ipucu false) ve kapanan eski lider takipçi gibi yayar ama gözlem yazmaz — kalan pod'un kendi "
            + "gözlemi korunur, yeni lider yaymayı sürdürür (eski hata: ölen pod'un gözlemi yeni lideri 150 sn susturuyordu)")
    void closingLeaderNeverSilencesTheSurvivor() {
        // B takipçiyken gözlem yazdı; şimdi B lider, A (eski lider) kapanıyor ve ipucu false
        assertThat(follower.refresh().orgFamilies()).isTrue();
        MonitoringMetricsExporter closingOldLeader = exporter(POD_A, false);
        closingOldLeader.onContextClosed(new ContextClosedEvent(mock(ApplicationContext.class)));
        clock.set(T0.plusSeconds(3));
        assertThat(closingOldLeader.refresh().orgFamilies()).isTrue();
        assertThat(row()).get().extracting(ClusterHealthStore.Observation::instanceId).as("A yazmadı").isEqualTo(POD_B);
        MonitoringMetricsExporter newLeader = exporter(POD_B, true);
        assertThat(newLeader.refresh().orgFamilies()).as("kendi gözlemi → yeni lider yayar").isTrue();
    }
}
