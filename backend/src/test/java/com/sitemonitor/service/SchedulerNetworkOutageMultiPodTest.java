package com.sitemonitor.service;

import com.sitemonitor.it.MultiPodTestSupport;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.atomic.AtomicBoolean;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

/**
 * Sertifika taramasının ağ kesintisi kararı İKİ {@code SchedulerService} pod'unda (2026-10-21, çok pod — MP-01): saatlik /
 * bayat taramalar pod'lar arasında el değiştirse de TEK açılış ve TEK çözüm postası; kesinti sürerken hiçbir pod sertifika
 * alarmı işlemez (envanter ekleme anındaki kapı {@code checkSingleDomainAsync} dâhil); pano her pod'da aynı.
 */
class SchedulerNetworkOutageMultiPodTest {

    private static final String ADMIN = "admin@example.com";

    private MultiPodTestSupport mp;
    private CertificateCheckerService checker;
    private EscalationService escalation;
    private EmailNotificationService email;
    private final AtomicBoolean networkDown = new AtomicBoolean();

    @BeforeEach
    void setUp() {
        mp = MultiPodTestSupport.create();
        mp.jdbc().execute("CREATE TABLE IF NOT EXISTS network_outage_events ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "detected_at VARCHAR(255) NOT NULL, resolved_at VARCHAR(255), "
                + "network_errors INTEGER, total_checks INTEGER, error_rate DOUBLE PRECISION, threshold DOUBLE PRECISION, "
                + "duration_ms BIGINT, status VARCHAR(16) NOT NULL, source VARCHAR(32), "
                + "alert_mail_status VARCHAR(255), alert_mail_claimed_ms BIGINT, alert_mail_attempts INTEGER, "
                + "resolved_mail_status VARCHAR(255), resolved_mail_claimed_ms BIGINT, resolved_mail_attempts INTEGER, "
                + "last_confirmed_at VARCHAR(30))");
        checker = mp.mock(CertificateCheckerService.class);
        escalation = mp.mock(EscalationService.class);
        email = mp.mock(EmailNotificationService.class);
        when(checker.checkAsync(anyString(), anyInt(), anyBoolean(), any(), any()))
                .thenAnswer(i -> CompletableFuture.completedFuture(result(i.getArgument(0))));
        when(checker.check(anyString(), anyInt(), anyBoolean(), any())).thenAnswer(i -> result(i.getArgument(0)));
        when(email.sendSystemAdminNetworkAlert(anyString(), any(), anyInt(), anyInt(), anyDouble(), anyDouble())).thenReturn("SENT");
        when(email.sendSystemAdminNetworkResolved(anyString(), any(), any(), anyLong(), anyInt(), anyInt(), anyDouble())).thenReturn("SENT");
    }

    @AfterEach
    void tearDown() {
        mp.close();
    }

    private Map<String, Object> result(String domain) {
        Map<String, Object> r = new LinkedHashMap<>();
        r.put("domain", domain);
        if (networkDown.get()) {
            r.put("status", "error");
            r.put("error_class", "NETWORK");
        } else {
            r.put("status", "valid");
        }
        return r;
    }

    private MultiPodTestSupport.Pod pod(int n) {
        return mp.pod(n, s -> {
            // Pod'un kendi kesinti servisi (kendi ezberi), ortak veritabanı + ortak saat — üretimde bean
            var outage = new com.sitemonitor.service.outage.CertNetworkOutageService(mp.jdbc(), email,
                    mp.mock(AppSettingsService.class)).withSystemAdminEmailDefault(ADMIN);
            ReflectionTestUtils.setField(outage, "clock", mp.clockSupplier());
            ReflectionTestUtils.setField(s, "certNetworkOutage", outage);
            ReflectionTestUtils.setField(s, "systemAdminEmail", ADMIN);
            ReflectionTestUtils.setField(s, "networkMinErrors", 3);
            ReflectionTestUtils.setField(s, "networkErrorRateThreshold", 0.5);
            ReflectionTestUtils.setField(s, "lockTtlMinutes", 10);
        });
    }

    private static List<Map<String, Object>> domains(int n) {
        List<Map<String, Object>> out = new ArrayList<>();
        for (int i = 0; i < n; i++) {
            Map<String, Object> d = new LinkedHashMap<>();
            d.put("domain", "d" + i + ".example.com");
            d.put("port", 443);
            out.add(d);
        }
        return out;
    }

    private static void sweep(MultiPodTestSupport.Pod p, int domains) {
        ReflectionTestUtils.invokeMethod(p.scheduler(), "runCheckForDomains", domains(domains), false);
    }

    private int ongoing() {
        return mp.jdbc().queryForObject("SELECT COUNT(*) FROM network_outage_events WHERE status = 'ONGOING'", Integer.class);
    }

    @Test
    @DisplayName("Kesinti A'da başlar, saatlik tur B'ye geçer, B'de biter: TEK açılış + TEK çözüm postası, TEK satır; kesintide alarm işlenmez")
    void outageAcrossPods_singleAlertSingleResolved() {
        var a = pod(1);
        var b = pod(2);

        networkDown.set(true);
        sweep(a, 10);
        sweep(b, 10);   // sonraki saat diğer pod'da
        sweep(a, 10);

        assertThat(ongoing()).isEqualTo(1);
        verify(email, times(1)).sendSystemAdminNetworkAlert(eq(ADMIN), any(), anyInt(), anyInt(), anyDouble(), anyDouble());
        verify(escalation, never()).processResults(anyList());
        assertThat(a.scheduler().isNetworkOutageActive()).isTrue();
        mp.advance(11_000);
        assertThat(b.scheduler().isNetworkOutageActive()).as("pano her pod'da aynı").isTrue();

        // Kesinti sürerken envanter ekleme (hangi pod alırsa) alarm işlemez
        b.scheduler().checkSingleDomainAsync("yeni.example.com", 443, false, null);
        verify(escalation, never()).processResults(anyList());

        // B'nin küçük bayat taraması (2 alan adı < min-errors 3) kesintiyi kapatamaz
        networkDown.set(false);
        sweep(b, 2);
        assertThat(ongoing()).isEqualTo(1);
        verify(email, never()).sendSystemAdminNetworkResolved(anyString(), any(), any(), anyLong(), anyInt(), anyInt(), anyDouble());
        verify(escalation, never()).processResults(anyList());

        // B'nin saatlik turu kapatır — tek çözüm postası; A'nın sonraki turu ikinci posta atmaz
        sweep(b, 10);
        sweep(a, 10);
        assertThat(ongoing()).isZero();
        verify(email, times(1)).sendSystemAdminNetworkResolved(eq(ADMIN), any(), any(), anyLong(), anyInt(), anyInt(), anyDouble());
        verify(escalation, times(2)).processResults(anyList());
        mp.advance(11_000);
        assertThat(a.scheduler().isNetworkOutageActive()).isFalse();
        assertThat(b.scheduler().isNetworkOutageActive()).isFalse();
        assertThat(a.scheduler().getNetworkOutageDetectedAt()).isNotNull().isEqualTo(b.scheduler().getNetworkOutageDetectedAt());
    }

    @Test
    @DisplayName("Kesinti yokken envanter ekleme anında alarm değerlendirmesi yapılır (kapı açık)")
    void noOutage_inventoryAddProcessesAlarm() {
        var a = pod(1);
        a.scheduler().checkSingleDomainAsync("yeni.example.com", 443, false, null);
        verify(escalation, times(1)).processResults(anyList());
    }
}
