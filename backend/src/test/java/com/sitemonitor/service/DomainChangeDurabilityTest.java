package com.sitemonitor.service;

import com.sitemonitor.it.MultiPodTestSupport;
import com.sitemonitor.model.DomainMonitor;
import com.sitemonitor.repository.DomainMonitorRepository;
import com.sitemonitor.service.monitoring.ChangeStates;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * Çok pod R1-B (2026-10-21, MP-13 / SWEEPS-2) — DOMAINMON_CHANGED liderlik devrinde KAYBOLMAZ, TAM BİR KEZ alarmlanır.
 *
 * <p>Değişmiş {@code domain_checks} satırı kaydedildiği anda tabandır; değerlendirme tur SONUNDA olduğu için kapı (kira
 * kaybedildi) ya da kapanış tur arasında düşürürse değişiklik eskiden kayboluyordu. Satır artık PENDING bekler; tarama
 * lideri her tikte (izlemenin vadesi gelmemiş olsa da) bekleyenleri değerlendirmeye alır.
 */
class DomainChangeDurabilityTest {

    static final String DOMAIN = "example.com";
    static final DateTimeFormatter ISO = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss").withZone(ZoneOffset.UTC);

    static final String DDL = "CREATE TABLE IF NOT EXISTS domain_checks ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, monitor_id BIGINT NOT NULL, checked_at VARCHAR(40), "
            + "status VARCHAR(16), changed BOOLEAN, manual BOOLEAN, change_detail VARCHAR(2000), registrar VARCHAR(200), "
            + "days_remaining INT, expiry_date VARCHAR(40), source VARCHAR(40), status_codes VARCHAR(2000), "
            + "nameservers VARCHAR(2000), transfer_lock VARCHAR(20), change_state VARCHAR(16))";

    MultiPodTestSupport mp;
    EscalationService escalation;
    DomainMonitor monitor;

    @BeforeEach
    void setUp() {
        mp = MultiPodTestSupport.create();
        mp.jdbc().execute(DDL);
        escalation = mp.mock(EscalationService.class);
        monitor = new DomainMonitor();
        monitor.setId(11L);
        monitor.setName("Alan A");
        monitor.setDomain(DOMAIN);
        monitor.setTeamId(7L);
        monitor.setActive(true);
        DomainMonitorRepository repo = mp.mock(DomainMonitorRepository.class);
        when(repo.findByActiveTrue()).thenReturn(List.of(monitor));
        when(repo.findAll()).thenReturn(List.of(monitor));
        when(repo.findById(11L)).thenReturn(Optional.of(monitor));
        // Zamanlanmış kontrol: değişiklik görür ve (gerçek servis gibi) PENDING satırı kaydeder.
        DomainCheckerService checker = mp.mock(DomainCheckerService.class);
        when(checker.check(any(DomainMonitor.class))).thenAnswer(i -> {
            String at = ISO.format(Instant.now());
            mp.jdbc().update("INSERT INTO domain_checks (monitor_id, checked_at, status, changed, manual, change_detail, "
                            + "registrar, days_remaining, expiry_date, source, status_codes, nameservers, transfer_lock, "
                            + "change_state) VALUES (?, ?, 'OK', TRUE, FALSE, ?, 'Reg', 200, '2027-05-01', 'RDAP', "
                            + "'clientTransferProhibited', 'ns3.example.net,ns4.example.net', 'CLIENT', ?)",
                    11L, at, "nameserver seti değişti;", ChangeStates.PENDING);
            return result(at);
        });
    }

    @AfterEach
    void tearDown() {
        mp.close();
    }

    static Map<String, Object> result(String at) {
        Map<String, Object> r = new LinkedHashMap<>();
        r.put("domain", DOMAIN);
        r.put("source", "RDAP");
        r.put("status", "OK");
        r.put("days_remaining", 200);
        r.put("expiry_date", "2027-05-01");
        r.put("registrar", "Reg");
        r.put("status_codes", List.of("clientTransferProhibited"));
        r.put("nameservers", List.of("ns3.example.net", "ns4.example.net"));
        r.put("changed", true);
        r.put("change_detail", "nameserver seti değişti;");
        r.put("epp_critical", false);
        r.put("epp_warn", false);
        r.put("transfer_lock", "CLIENT");
        r.put("blacklist_status", "SKIPPED");
        r.put("checked_at", at);
        return r;
    }

    String state() {
        List<String> s = mp.jdbc().queryForList("SELECT change_state FROM domain_checks WHERE monitor_id = 11 ORDER BY id",
                String.class);
        return s.isEmpty() ? null : s.get(s.size() - 1);
    }

    int changedAlarms() {
        return (int) org.mockito.Mockito.mockingDetails(escalation).getInvocations().stream()
                .filter(i -> i.getMethod().getName().equals("processConfirmedOutage"))
                .filter(i -> EscalationService.TYPE_DOMAINMON_CHANGED.equals(i.getArgument(1)))
                .count();
    }

    @Test
    @DisplayName("A'nın turu değişikliği kaydetti ama değerlendirme kapıda düştü → B (vadesi gelmemiş izleme) bekleyeni "
            + "değerlendirir → TAM BİR alarm; sonraki tik ikinciyi açmaz")
    void droppedEvaluationRecoveredByNewLeader() {
        MonitoringMultiPodKit.PodWithMos a = MonitoringMultiPodKit.podWithMos(mp, 1);
        MonitoringMultiPodKit.PodWithMos b = MonitoringMultiPodKit.podWithMos(mp, 2);
        ReflectionTestUtils.setField(b.mos(), "confirmExecutor", MonitoringMultiPodKit.immediate());
        a.mos().setScheduledResultsFence(() -> false);   // turun ortasında kira kaybedildi: değerlendirme düşer

        a.scheduler().runDomainChecks();
        assertThat(state()).isEqualTo(ChangeStates.PENDING);
        assertThat(changedAlarms()).isZero();

        mp.advance(MonitoringMultiPodKit.TTL + 1_000);
        b.scheduler().runDomainChecks();                 // izleme günlük — vadesi gelmedi; bekleyen satır yine işlenir
        assertThat(changedAlarms()).as("değişiklik KAYBOLMADI").isEqualTo(1);
        assertThat(state()).isEqualTo(ChangeStates.ALARMED);
        @SuppressWarnings("unchecked")
        ArgumentCaptor<Map<String, Object>> ctx = ArgumentCaptor.forClass(Map.class);
        verify(escalation).processConfirmedOutage(eq(DOMAIN), eq(EscalationService.TYPE_DOMAINMON_CHANGED), anyString(),
                ctx.capture());
        assertThat(ctx.getValue()).containsEntry("monitor_id", 11L)
                .containsEntry("change_detail", "nameserver seti değişti;");

        mp.advance(3_600_000L);
        b.scheduler().runDomainChecks();
        assertThat(changedAlarms()).isEqualTo(1);
    }

    @Test
    @DisplayName("Normal tur: aynı turda değerlendirilir → ALARMED; bekleyen satır aynı turda İKİNCİ kez eklenmez")
    void sameSweep_alarmedOnce() {
        MonitoringMultiPodKit.PodWithMos a = MonitoringMultiPodKit.podWithMos(mp, 1);
        ReflectionTestUtils.setField(a.mos(), "confirmExecutor", MonitoringMultiPodKit.immediate());
        a.scheduler().runDomainChecks();
        assertThat(changedAlarms()).isEqualTo(1);
        assertThat(state()).isEqualTo(ChangeStates.ALARMED);
    }

    @Test
    @DisplayName("Bekleyen satırın izlemesinde değişiklik alarmı kapatıldıysa SUPPRESSED; 6 saatten eskisi EXPIRED — alarm yok")
    void suppressedAndExpired() {
        MonitoringMultiPodKit.PodWithMos a = MonitoringMultiPodKit.podWithMos(mp, 1);
        ReflectionTestUtils.setField(a.mos(), "confirmExecutor", MonitoringMultiPodKit.immediate());
        // Önce vade dolsun diye izleme bir tur koşsun (satır ALARMED); sonra iki elle eklenmiş bekleyen satır.
        a.scheduler().runDomainChecks();
        mp.jdbc().update("INSERT INTO domain_checks (monitor_id, checked_at, changed, manual, change_state) VALUES (?, ?, TRUE, FALSE, ?)",
                11L, ISO.format(Instant.now().minusSeconds(7 * 3600)), ChangeStates.PENDING);
        monitor.setChangeAlert(false);
        mp.jdbc().update("INSERT INTO domain_checks (monitor_id, checked_at, changed, manual, change_state) VALUES (?, ?, TRUE, FALSE, ?)",
                11L, ISO.format(Instant.now().minusSeconds(60)), ChangeStates.PENDING);

        mp.advance(3_600_000L);
        a.scheduler().runDomainChecks();
        List<String> states = mp.jdbc().queryForList("SELECT change_state FROM domain_checks WHERE monitor_id = 11 ORDER BY id",
                String.class);
        assertThat(states).containsExactly(ChangeStates.ALARMED, ChangeStates.EXPIRED, ChangeStates.SUPPRESSED);
        assertThat(changedAlarms()).isEqualTo(1);
    }
}
