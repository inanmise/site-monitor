    @Test
    @DisplayName("Teyit zinciri lider A'da öldü → yeni lider B bekleyen değişikliği yeniden teyit eder → TAM BİR alarm; "
            + "A'nın geç biten zinciri ikinciyi açmaz")
    void pendingChangeSurvivesHandover_alarmsExactlyOnce() {
        MonitoringMultiPodKit.PodWithMos a = MonitoringMultiPodKit.podWithMos(mp, 1);
        MonitoringMultiPodKit.PodWithMos b = MonitoringMultiPodKit.podWithMos(mp, 2);
        MonitoringMultiPodKit.Manual killed = new MonitoringMultiPodKit.Manual();
        ReflectionTestUtils.setField(a.mos(), "confirmExecutor", killed);   // A'nın zinciri hiç ilerlemez (pod devredildi)
        ReflectionTestUtils.setField(b.mos(), "confirmExecutor", MonitoringMultiPodKit.immediate());

        a.scheduler().runDnsChecks();                                         // A lider: değişiklik görülür, satır PENDING
        assertThat(state(5L)).isEqualTo(ChangeStates.PENDING);
        assertThat(killed.pending()).as("A'da teyit zinciri başladı (ve öldü)").isEqualTo(1);
        assertThat(dnsChangedAlarms()).isZero();

        mp.advance(MonitoringMultiPodKit.TTL + 1_000);                        // A'nın kirası doldu
        b.scheduler().runDnsChecks();                                         // B lider: bekleyen satırı yeniden teyit eder
        assertThat(dnsChangedAlarms()).as("değişiklik KAYBOLMADI").isEqualTo(1);
        assertThat(state(5L)).isEqualTo(ChangeStates.ALARMED);
        @SuppressWarnings("unchecked")
        ArgumentCaptor<Map<String, Object>> ctx = ArgumentCaptor.forClass(Map.class);
        verify(escalation).processConfirmedOutage(eq(DOMAIN), eq(EscalationService.TYPE_DNS_CHANGED), anyString(), ctx.capture());
        assertThat(ctx.getValue()).containsEntry("monitor_id", 5L)
                .containsEntry("old_values", List.of("1.1.1.1")).containsEntry("new_values", List.of("2.2.2.2"));

        // A'nın zinciri geç ilerler (zombi pod): son adımda kapı kirayı kaybettiğini görür (LOST → sıfırlama) — ikinci alarm yok.
        killed.drain();
        assertThat(dnsChangedAlarms()).isEqualTo(1);

        // Sonraki tur: bekleyen satır kalmadı.
        mp.advance(60_000);
        b.scheduler().runDnsChecks();
        assertThat(dnsChangedAlarms()).isEqualTo(1);
    }

