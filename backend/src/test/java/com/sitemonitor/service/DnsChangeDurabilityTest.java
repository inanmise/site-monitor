    @Test
    @DisplayName("Aynı alan adında iki izlemenin değişikliği aynı anda teyit edilir → alarm kilidi çakışması YENİDEN DENENİR → iki bildirim")
    void twoMonitorsSameDomain_lockCollisionRetried_twoNotifications() {
        MonitoringOutageService s = MonitoringMultiPodKit.mos(mp);
        MonitoringMultiPodKit.Manual ex = new MonitoringMultiPodKit.Manual();
        ReflectionTestUtils.setField(s, "confirmExecutor", ex);
        ReflectionTestUtils.setField(s, "changeLockRetryMs", 4_242L);
        String at = ISO.format(Instant.now());
        insertPending(5L, "A", "1.1.1.1", "2.2.2.2", at);
        insertPending(6L, "MX", "mx1.example.com", "mx2.example.com", at);
        // Alarm kilidini "başka yazar" tutuyor (ör. eşzamanlı biten diğer zincir).
        mp.jdbc().update("INSERT INTO scheduler_lock(name, locked_by, locked_until) VALUES (?, ?, ?)",
                "mon-alert:" + EscalationService.TYPE_DNS_CHANGED + ":" + DOMAIN, "other", "2999-01-01T00:00:00");

        s.handleDnsSweep(List.of(), List.of(), List.of(change(5L, "A", "1.1.1.1", "2.2.2.2", at),
                change(6L, "MX", "mx1.example.com", "mx2.example.com", at)), List.of(), List.of());
        for (int i = 0; i < 10 && !ex.pendingDelays().contains(4_242L); i++) ex.runRound();
        assertThat(ex.pendingDelays()).as("kilit çakışması yeniden deneme planladı (eskiden sessizce atlanıyordu)")
                .containsOnly(4_242L).hasSize(2);
        assertThat(dnsChangedAlarms()).isZero();

        mp.jdbc().update("DELETE FROM scheduler_lock WHERE locked_by = 'other'");   // diğer yazar bitirdi
        ex.drain();
        assertThat(dnsChangedAlarms()).as("iki izlemenin değişikliği de bildirildi").isEqualTo(2);
        assertThat(state(5L)).isEqualTo(ChangeStates.ALARMED);
        assertThat(state(6L)).isEqualTo(ChangeStates.ALARMED);
        assertThat(s.activeConfirmations(null)).isEmpty();
    }

