package com.sitemonitor.service;

import com.sitemonitor.it.MultiPodTestSupport;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.time.Duration;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * SMTP 421 yetim satır süpürücüsü (2026-10-21, çok pod R1 / MP-06): gönderen pod öldüğü için sonucu ASLA gelmeyecek
 * {@code QUEUED_RETRY} satırları eşikten (zincir + pay, en az 20 dk) sonra koşullu UPDATE'le FAILED olur; genç satır, başka
 * durumlar ve geriye bakış penceresinin dışı dokunulmaz; iki süpürücü aynı anda koşsa da her satır bir kez yazılır.
 */
class MailRetryOrphanSweeperTest {

    static final DateTimeFormatter ISO =
            DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss").withZone(ZoneOffset.UTC);

    MultiPodTestSupport mp;
    EmailNotificationService email;

    @BeforeEach
    void setUp() {
        mp = MultiPodTestSupport.create();
        mp.jdbc().execute("CREATE TABLE notification_logs (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "alert_event_id BIGINT NOT NULL, sent_at VARCHAR(255), email_status VARCHAR(255), retry_alive_at VARCHAR(30))");
        email = mock(EmailNotificationService.class);
        when(email.currentRetryChainDuration()).thenReturn(EmailNotificationService.retryChainDuration(90_000L));
    }

    @AfterEach
    void tearDown() {
        mp.close();
    }

    long row(Instant sentAt, String status) {
        mp.jdbc().update("INSERT INTO notification_logs(alert_event_id, sent_at, email_status) VALUES (1, ?, ?)",
                ISO.format(sentAt), status);
        return mp.jdbc().queryForObject("SELECT max(id) FROM notification_logs", Long.class);
    }

    String status(long id) {
        return mp.jdbc().queryForObject("SELECT email_status FROM notification_logs WHERE id = ?", String.class, id);
    }

    @Test
    @DisplayName("25 dk eski QUEUED_RETRY → FAILED (sonuç yok); 5 dk eski / SENT / 3 gün eski dokunulmaz")
    void orphanedRowsFinalised_othersUntouched() {
        Instant now = Instant.now();
        long old = row(now.minus(Duration.ofMinutes(25)), "QUEUED_RETRY: 421 4.4.2");
        long young = row(now.minus(Duration.ofMinutes(5)), "QUEUED_RETRY: 421");
        long sent = row(now.minus(Duration.ofMinutes(40)), "SENT");
        long ancient = row(now.minus(Duration.ofDays(3)), "QUEUED_RETRY: 421");

        MailRetryOrphanSweeper sweeper = new MailRetryOrphanSweeper(mp.jdbc(), email);
        assertThat(sweeper.sweep(now)).isEqualTo(1);

        assertThat(status(old)).isEqualTo(EmailNotificationService.STATUS_RETRY_ORPHANED);
        assertThat(status(young)).startsWith("QUEUED_RETRY");
        assertThat(status(sent)).isEqualTo("SENT");
        assertThat(status(ancient)).as("geriye bakış dışı — bu sürümden önce takılmış satıra dokunulmaz").startsWith("QUEUED_RETRY");
        assertThat(sweeper.sweep(now)).as("ikinci tur yazmaz (koşullu)").isZero();
    }

    @Test
    @DisplayName("eşik: varsayılan gecikmeyle 20 dk taban; büyük gecikmede zincir + 5 dk")
    void orphanAgeFollowsRetryChain() {
        MailRetryOrphanSweeper sweeper = new MailRetryOrphanSweeper(mp.jdbc(), email);
        assertThat(sweeper.orphanAge()).isEqualTo(Duration.ofMinutes(20));
        when(email.currentRetryChainDuration()).thenReturn(EmailNotificationService.retryChainDuration(300_000L));   // 35 dk
        assertThat(sweeper.orphanAge()).isEqualTo(Duration.ofMinutes(40));
    }

    @Test
    @DisplayName("iki pod'un süpürücüsü aynı anda → her yetim satır TEK kez yazılır (toplam güncelleme = satır sayısı)")
    void twoSweepers_eachRowOnce() {
        Instant now = Instant.now();
        for (int i = 0; i < 30; i++) row(now.minus(Duration.ofMinutes(30 + i)), "QUEUED_RETRY: 421");
        MailRetryOrphanSweeper a = new MailRetryOrphanSweeper(mp.jdbc(), email);
        MailRetryOrphanSweeper b = new MailRetryOrphanSweeper(mp.jdbc(), email);
        List<Integer> n = mp.race(() -> a.sweep(now), () -> b.sweep(now));
        assertThat(n.get(0) + n.get(1)).isEqualTo(30);
        assertThat(mp.jdbc().queryForObject("SELECT count(*) FROM notification_logs WHERE email_status LIKE 'QUEUED_RETRY%'",
                Integer.class)).isZero();
    }

    @Test
    @DisplayName("zamanlanmış tur kilit altında koşar (scheduler_lock 'mail-retry-orphans'); kilit başkasındaysa atlanır")
    void scheduledSweepUsesLock() {
        Instant now = Instant.now();
        long old = row(now.minus(Duration.ofMinutes(25)), "QUEUED_RETRY: 421");
        SchedulerService scheduler = mock(SchedulerService.class);
        when(scheduler.callWithSchedulerLock(org.mockito.ArgumentMatchers.eq(MailRetryOrphanSweeper.LOCK), any()))
                .thenReturn(Optional.empty());   // kilit başka pod'da
        MailRetryOrphanSweeper sweeper = new MailRetryOrphanSweeper(mp.jdbc(), email);
        sweeper.setScheduler(scheduler);
        sweeper.scheduledSweep();
        assertThat(status(old)).startsWith("QUEUED_RETRY");

        when(scheduler.callWithSchedulerLock(org.mockito.ArgumentMatchers.eq(MailRetryOrphanSweeper.LOCK), any()))
                .thenAnswer(inv -> Optional.ofNullable(((java.util.function.Supplier<?>) inv.getArgument(1)).get()));
        sweeper.scheduledSweep();
        assertThat(status(old)).isEqualTo(EmailNotificationService.STATUS_RETRY_ORPHANED);
    }

    @Test
    @DisplayName("inceleme N4: canlı pod'un tazelediği satır yetim sayılmaz; damgası bayatlayan ya da 2 saati geçen satır kapanır")
    void aliveRowsAreNotOrphaned() {
        Instant now = Instant.now();
        long alive = row(now.minus(Duration.ofMinutes(40)), "QUEUED_RETRY: 421");
        mp.jdbc().update("UPDATE notification_logs SET retry_alive_at = ? WHERE id = ?", ISO.format(now.minus(Duration.ofMinutes(3))), alive);
        long staleAlive = row(now.minus(Duration.ofMinutes(40)), "QUEUED_RETRY: 421");
        mp.jdbc().update("UPDATE notification_logs SET retry_alive_at = ? WHERE id = ?", ISO.format(now.minus(Duration.ofMinutes(20))), staleAlive);
        long tooOld = row(now.minus(Duration.ofHours(3)), "QUEUED_RETRY: 421");
        mp.jdbc().update("UPDATE notification_logs SET retry_alive_at = ? WHERE id = ?", ISO.format(now.minus(Duration.ofMinutes(1))), tooOld);

        MailRetryOrphanSweeper sweeper = new MailRetryOrphanSweeper(mp.jdbc(), email);
        assertThat(sweeper.sweep(now)).isEqualTo(2);
        assertThat(status(alive)).as("canlı pod'un yeniden denemesi sürüyor").startsWith("QUEUED_RETRY");
        assertThat(status(staleAlive)).isEqualTo(EmailNotificationService.STATUS_RETRY_ORPHANED);
        assertThat(status(tooOld)).as("üst sınır — sonsuz bekleme yok").isEqualTo(EmailNotificationService.STATUS_RETRY_ORPHANED);
    }

    @Test
    @DisplayName("inceleme N4: her pod turun başında KENDİ bekleyenlerini tazeler (kilitten bağımsız); kolon yoksa eski ifade")
    void heartbeatRunsOnEveryPodAndLegacyFallback() {
        MailRetryOrphanSweeper sweeper = new MailRetryOrphanSweeper(mp.jdbc(), email);
        sweeper.scheduledSweep();
        org.mockito.Mockito.verify(email).heartbeatPendingRetries(org.mockito.ArgumentMatchers.anyString());

        mp.jdbc().execute("ALTER TABLE notification_logs DROP COLUMN retry_alive_at");
        Instant now = Instant.now();
        long old = row(now.minus(Duration.ofMinutes(25)), "QUEUED_RETRY: 421");
        assertThat(sweeper.sweep(now)).isEqualTo(1);
        assertThat(status(old)).isEqualTo(EmailNotificationService.STATUS_RETRY_ORPHANED);
        assertThat(sweeper.aliveTtl()).isEqualTo(MailRetryOrphanSweeper.MIN_ALIVE_TTL);
        sweeper.sweepIntervalMs = 30 * 60_000L;
        assertThat(sweeper.aliveTtl()).isEqualTo(Duration.ofMinutes(90));
    }
}
