package com.sitemonitor.service.oncallroutine;

import com.sitemonitor.model.AppUser;
import com.sitemonitor.model.Team;
import com.sitemonitor.repository.AppUserRepository;
import com.sitemonitor.repository.TeamRepository;
import com.sitemonitor.service.oncallroutine.OnCallRoutineService.Actor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.PlatformTransactionManager;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayOutputStream;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * Nöbet rutini H2 testlerinin ortak kurulumu (2026-11-26): gerçek {@link OnCallRoutineStore} + {@link OnCallRoutineService}
 * (H2, PostgreSQL kipi), sahte takım / kullanıcı depoları, sabit saat. Testler COMMIT eder ({@code NOT_SUPPORTED}) — her
 * testin ÖNCESİNDE ve SONRASINDA {@link #clean()} çağrılır.
 */
final class OnCallRoutineTestRig {

    static final Long TEAM = 7L;
    static final String TEAM_NAME = "Ödeme Sistemleri";
    /** Silme sırası (görsel → sorun → … → takım satırı). */
    static final List<String> TABLES = List.of("oncall_routine_problem_images", "oncall_routine_problems",
            "oncall_routine_items", "oncall_routine_events", "oncall_routine_notices", "oncall_routine_handovers",
            "oncall_routine_assignments", "oncall_routine_days", "oncall_routine_template_versions", "oncall_routine_teams");

    /** Pazartesi 2026-11-23 09:00 İstanbul. */
    static final Instant MON_0900 = Instant.parse("2026-11-23T06:00:00Z");
    /** Perşembe 2026-11-26 09:30 İstanbul. */
    static final Instant THU_0930 = Instant.parse("2026-11-26T06:30:00Z");

    static final Actor A = new Actor(10L, "Kişi A", "N10");
    static final Actor B = new Actor(11L, "Kişi B", "N11");

    final JdbcTemplate jdbc;
    final TeamRepository teams = mock(TeamRepository.class);
    final AppUserRepository users = mock(AppUserRepository.class);
    final OnCallRoutineStore store;
    final OnCallRoutineService svc;
    /** id → [id, username, displayName, email, active]; üyeler takımın etkin üyeleri. */
    final Map<Long, Object[]> people = new ConcurrentHashMap<>();
    final Map<Long, Boolean> members = new ConcurrentHashMap<>();
    final Map<Long, Team> teamRows = new ConcurrentHashMap<>();

    OnCallRoutineTestRig(JdbcTemplate jdbc, PlatformTransactionManager txm) {
        this.jdbc = jdbc;
        // H2'nin PostgreSQL kipi (ON CONFLICT için şart) BLOB türünü tanımaz; create-drop bu tabloyu kuramaz. PostgreSQL'de
        // tür BYTEA (postgres-it kapsar); burada aynı sütunlarla VARBINARY olarak kurulur.
        jdbc.execute("CREATE TABLE IF NOT EXISTS oncall_routine_problem_images (id BIGINT GENERATED BY DEFAULT AS IDENTITY "
                + "PRIMARY KEY, problem_id BIGINT NOT NULL, team_id BIGINT NOT NULL, content_type VARCHAR(20) NOT NULL, "
                + "size_bytes BIGINT NOT NULL, width INTEGER NOT NULL, height INTEGER NOT NULL, file_name VARCHAR(200), "
                + "created_at VARCHAR(30), created_by_name VARCHAR(200), data VARBINARY(10485760) NOT NULL)");
        this.store = new OnCallRoutineStore(jdbc);
        this.svc = new OnCallRoutineService(store, teams, users, txm);
        at(THU_0930);
        team(TEAM, TEAM_NAME, true);
        when(teams.findById(any())).thenAnswer(i -> Optional.ofNullable(teamRows.get((Long) i.getArgument(0))));
        when(teams.findAllById(any())).thenAnswer(i -> {
            List<Team> out = new ArrayList<>();
            for (Object id : (Iterable<?>) i.getArgument(0)) if (teamRows.containsKey((Long) id)) out.add(teamRows.get((Long) id));
            return out;
        });
        when(users.findOnCallPersonRows(any())).thenAnswer(i -> {
            List<Object[]> out = new ArrayList<>();
            for (Object id : (Collection<?>) i.getArgument(0)) {
                Object[] r = people.get((Long) id);
                if (r != null) out.add(r.clone());
            }
            return out;
        });
        when(users.findActiveMemberRowsOfTeams(any())).thenAnswer(i -> {
            List<Object[]> out = new ArrayList<>();
            for (Map.Entry<Long, Boolean> m : members.entrySet()) {
                Object[] p = people.get(m.getKey());
                if (p == null || !m.getValue() || Boolean.FALSE.equals(p[4])) continue;
                out.add(new Object[] {p[0], p[1], p[2], null, null, TEAM, null, "USER"});
            }
            return out;
        });
        when(users.findById(anyLong())).thenAnswer(i -> {
            Object[] p = people.get((Long) i.getArgument(0));
            if (p == null) return Optional.empty();
            AppUser u = new AppUser();
            u.setId((Long) p[0]);
            u.setUsername((String) p[1]);
            u.setDisplayName((String) p[2]);
            u.setEmail((String) p[3]);
            u.setActive((Boolean) p[4]);
            return Optional.of(u);
        });
        person(10L, "N10", "Kişi A", true, true);
        person(11L, "N11", "Kişi B", true, true);
    }

    void clean() {
        for (String t : TABLES) jdbc.update("DELETE FROM " + t);
    }

    void at(Instant now) {
        svc.clock = Clock.fixed(now, ZoneOffset.UTC);
    }

    Team team(Long id, String name, boolean active) {
        Team t = new Team();
        t.setId(id);
        t.setName(name);
        t.setActive(active);
        teamRows.put(id, t);
        return t;
    }

    void person(long id, String username, String name, boolean active, boolean member) {
        people.put(id, new Object[] {id, username, name, username.toLowerCase() + "@example.com", active});
        members.put(id, member);
    }

    /** Sabah bölümü (d1, d2 zorunlu; opt isteğe bağlı) + haftalık Cuma görevi. */
    static Map<String, Object> template() {
        return Map.of("sections", List.of(
                Map.of("id", "s1", "title", "Sabah kontrolleri", "tasks", List.of(
                        Map.of("id", "d1", "title", "Kuyruklar"),
                        Map.of("id", "d2", "title", "Yedek işleri"),
                        Map.of("id", "opt", "title", "İsteğe bağlı bakış", "required", false))),
                Map.of("id", "s2", "title", "Haftalık", "tasks", List.of(
                        Map.of("id", "w1", "title", "Yedek geri yükleme denemesi", "frequency", "WEEKLY", "weekday", 5)))));
    }

    /** {@link #template()} + d3 (yeni sürüm). */
    static Map<String, Object> templateWithD3() {
        return Map.of("sections", List.of(
                Map.of("id", "s1", "title", "Sabah kontrolleri", "tasks", List.of(
                        Map.of("id", "d1", "title", "Kuyruklar"),
                        Map.of("id", "d2", "title", "Yedek işleri"),
                        Map.of("id", "d3", "title", "Sertifika uyarıları"),
                        Map.of("id", "opt", "title", "İsteğe bağlı bakış", "required", false))),
                Map.of("id", "s2", "title", "Haftalık", "tasks", List.of(
                        Map.of("id", "w1", "title", "Yedek geri yükleme denemesi", "frequency", "WEEKLY", "weekday", 5)))));
    }

    /** Şablonu saklı sürümün üstüne kaydeder (CAS doğru sürümle). */
    OnCallRoutineService.SaveResult saveTemplate(Map<String, Object> tpl) {
        OnCallRoutineStore.TeamRow row = store.team(TEAM);
        return svc.saveTemplate(TEAM, row == null ? 0 : row.templateVersion(), tpl, "EDITOR", A);
    }

    OnCallRoutineService.TeamCtx ctx() {
        return svc.ctx(TEAM);
    }

    int count(String table) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM " + table + " WHERE team_id = ?", Integer.class, TEAM);
        return n == null ? 0 : n;
    }

    int countEvents(String kind) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM oncall_routine_events WHERE team_id = ? AND kind = ?",
                Integer.class, TEAM, kind);
        return n == null ? 0 : n;
    }

    static byte[] png(int side) {
        try {
            BufferedImage img = new BufferedImage(side, side, BufferedImage.TYPE_INT_RGB);
            for (int x = 0; x < side; x++) img.setRGB(x, x, 0x336699);
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            ImageIO.write(img, "png", out);
            return out.toByteArray();
        } catch (java.io.IOException e) {
            throw new IllegalStateException(e);
        }
    }
}
