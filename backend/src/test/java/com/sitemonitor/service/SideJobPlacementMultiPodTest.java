        idle(b);
        tlsB.scheduledTick();                                // aynı aralık: sabit gecikme bekletir (FX-SIDE #1) …
        assertThat(b.runner().runDeferredNow()).isEqualTo(1);   // … bekleme dolunca da tur alınmış → yoklama yok
