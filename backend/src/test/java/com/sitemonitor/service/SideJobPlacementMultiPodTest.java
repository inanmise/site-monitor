    // ── Tur tabanlı ağır işler: takipçi alınca lider bırakır ───────────────────────────────────────────────────────

    @Test
    @DisplayName("Bayat sertifika taraması ×20: takipçi alır, lider bırakır (dönem başına bir koşu); takipçi durursa lider en geç 2 "
            + "periyotta, takipçi ölürse (heartbeat biter) hemen geri alır")
    void staleSweep_followerClaims_leaderYields_thenFallback() {
        P a = pod(1);
        P b = pod(2);
        LatestCheckRepository latest = mp.mock(LatestCheckRepository.class);
        long period = 5 * MIN;
        beat(1);
        beat(2);
        lead(a);
        b.s().checkStaleInventory();                         // ilk tur takipçide (sıra rastlantı)
        idle(b);
        assertThat(calls(latest, "findByCheckedAtGreaterThanEqual")).isEqualTo(1);
        for (int k = 0; k < ROUNDS; k++) {
            mp.advance(period);
            beat(1);
            beat(2);
            lead(a);
            a.s().checkStaleInventory();                     // lider ÖNCE tıklasa da bırakır (kanıt: takipçi TAMAMLADI)
            idle(a);
            b.s().checkStaleInventory();
            idle(b);
            assertThat(calls(latest, "findByCheckedAtGreaterThanEqual")).as("tur %d", k).isEqualTo(k + 2);
            assertThat(roundRow("cert-stale")).containsEntry("claimed_by", MultiPodTestSupport.owner(2));
        }
        assertThat(job(a.runner(), "cert-stale").yieldedCount()).isEqualTo(ROUNDS);
        assertThat(job(a.runner(), "cert-stale").runs()).isZero();

        long before = calls(latest, "findByCheckedAtGreaterThanEqual");
        // takipçi canlı ama bayat tıkı durdu: lider kanıt 2 periyot eskiyene dek bırakır, sonra alır
        mp.advance(period);
        beat(1);
        beat(2);
        lead(a);
        a.s().checkStaleInventory();
        idle(a);
        mp.advance(period);
        beat(1);
        beat(2);
        lead(a);
        a.s().checkStaleInventory();
        idle(a);
        assertThat(calls(latest, "findByCheckedAtGreaterThanEqual")).as("2 periyot içinde bırakır").isEqualTo(before);
        mp.advance(period);
        beat(1);
        beat(2);
        lead(a);
        a.s().checkStaleInventory();
        idle(a);
        assertThat(calls(latest, "findByCheckedAtGreaterThanEqual")).as("kanıt eskidi → lider aldı").isEqualTo(before + 1);
        assertThat(roundRow("cert-stale")).containsEntry("claimed_by", MultiPodTestSupport.owner(1));

        // takipçi yeniden alır, sonra ÖLÜR (heartbeat biter): lider canlılık penceresi (3 dk) dolunca hemen alır
        mp.advance(period);
        beat(1);
        beat(2);
        b.s().checkStaleInventory();
        idle(b);
        long afterB = calls(latest, "findByCheckedAtGreaterThanEqual");
        assertThat(afterB).isEqualTo(before + 2);
        mp.advance(period);                                  // b'nin son heartbeat'i 5 dk önce → canlı değil
        beat(1);
        lead(a);
        a.s().checkStaleInventory();
        idle(a);
        assertThat(calls(latest, "findByCheckedAtGreaterThanEqual")).as("ölü takipçiye bırakılmaz").isEqualTo(afterB + 1);
    }

