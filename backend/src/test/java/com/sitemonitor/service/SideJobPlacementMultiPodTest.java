    /** R3-1 pod'u: koşucu (2 iş parçacığı), yerleşim (20 sn erteleme), canlılık (kendi kimliği, ortak saat). */
    P pod(int n) {
        Pod p = mp.pod(n, this::tune);
        PodLiveness live = new PodLiveness(mp.jdbc(), p.owner(), mp.clockSupplier());
        SideJobPlacement placement = new SideJobPlacement(yieldOn::get, live, DEFER_MS);
        SideJobRunner runner = new SideJobRunner(2, mp.clockSupplier());
        runner.setPlacement(placement);
        runners.add(runner);
        p.scheduler().setSideJobPlacement(placement);
        p.scheduler().setSideJobRunner(runner);
        return new P(p, runner, live);
    }

    /** 20.167.0 komşusu: küme kaydı + kilit servisi VAR, R3-1 parçaları YOK (erteleme / bırakma / koşucu bilmez). */
    P oldPod(int n) {
        return new P(mp.pod(n, this::tune), null, null);
    }

