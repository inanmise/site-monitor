    @Test
    @DisplayName("kısaltırsam: zaman aşımlı COUNT; düşerse histogram; o da yoksa tekdüze; geçersiz kural / taban altı → alan hatası")
    void whatIf() {
        seedFourteenDays();
        source.count = 1234L;
        Map<String, Object> c = svc.whatIf("series-port", 90);
        assertThat(c.get("rows")).isEqualTo(1234L);
        assertThat(c.get("rows_method")).isEqualTo("count");
        assertThat(c.get("current_days")).isEqualTo(180);
        assertThat(c.get("compliance")).isEqualTo(false);
        assertThat(c.get("cutoff")).isEqualTo("2026-08-15T10:00:00");
        assertThat((Long) c.get("bytes_estimate")).isPositive();

        source.count = null;
        List<String> bounds = List.of("2026-08-01T00:00:00", "2026-09-01T00:00:00", "2026-10-01T00:00:00", "2026-11-13T00:00:00");
        source.histograms.put("port_checks.checked_at", bounds);
        Map<String, Object> h = svc.whatIf("series-port", 90);
        assertThat(h.get("rows_method")).isEqualTo("histogram");
        assertThat((Long) h.get("rows")).isBetween(1L, 1_000_000L);

        source.histograms.clear();
        Map<String, Object> u = svc.whatIf("series-port", 30);
        assertThat(u.get("rows_method")).isEqualTo("uniform");
        assertThat(u.get("rows")).isEqualTo(0L);    // en eski 30 gün önce → 30 güne kısaltmak bir şey silmez

        assertThatThrownBy(() -> svc.whatIf("nope", 90)).isInstanceOf(FieldValidationException.class);
        assertThatThrownBy(() -> svc.whatIf("series-port", 7)).isInstanceOf(FieldValidationException.class);
        assertThatThrownBy(() -> svc.whatIf("dns-records-orphan", 90)).isInstanceOf(FieldValidationException.class);
        Map<String, Object> pii = svc.whatIf("audit-log", 180);
        assertThat(pii.get("compliance")).isEqualTo(true);
    }

    @Test
    @DisplayName("kısaltırsam: gün ve saat kovası kuralları kesimi kırpar (RetentionService ile aynı biçim)")
    void cutoffFormats() {
        RetentionPolicy daily = com.sitemonitor.service.retention.RetentionCatalog.byId("rollup-daily").orElseThrow();
        RetentionPolicy hourly = com.sitemonitor.service.retention.RetentionCatalog.byId("rollup-hourly").orElseThrow();
        assertThat(DbGrowthService.cutoffFor(daily, 100, NOW)).isEqualTo("2026-08-05");
        assertThat(DbGrowthService.cutoffFor(hourly, 100, NOW)).isEqualTo("2026-08-05T10");
        assertThat(LocalDate.ofInstant(NOW, ZoneId.of("Europe/Istanbul")).toString()).isEqualTo(TODAY);
    }
