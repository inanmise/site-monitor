/**
 * Çok pod Sürüm 3-4 paket C2 — L-1 İFADE DÖKÜMÜ (tasarım R3-4 §9.1; 3-3'ün {@code DistributedChecksOffSqlTranscriptTest}
 * deseni): anahtar AÇILIŞTAN BERİ KAPALI ve 3-4'ün TÜM parçaları üretimdeki gibi kurulu ({@link CertChunking},
 * {@link JdbcCertSweepStore} — kendi zaman aşımlı şablonları + 3-3'ün veritabanı-çapalı saati, {@link CertChunkWorker} — Spring
 * kurucusu, tembel başlatıcı kayıtlı, {@link CertRunCoordinator} — Spring kurucusu, tembel sağlayıcılar, {@link SchedulerCertChunks},
 * gerçek {@link PodLiveness}) iken saatlik / bayat / tam sertifika turları, hazır / ayar / kapanış olayları 3-4 parçası HİÇ
 * olmayan kurulumla birebir AYNI:
 * <ul>
 *   <li>gerçek veritabanı SQL çoklu kümesi (kayıtlı veri kaynağı: iş kilidi, cron turu, toplu kesinti satırı, scan_runs, kira) —
 *       {@code cert_sweep_*}, {@code system_heartbeat} (PodLiveness), {@code issuer_dn} okuması ve DB saati çapası YOK;</li>
 *   <li>bağımlılık dökümü (denetleyici, {@code CertificateService}, {@code EscalationService}, envanter / son kontrol depoları,
 *       e-posta — JPA ifadelerinin karşılığı) sıralı ve normalleştirilmiş olarak eşit;</li>
 *   <li>INFO ve üstü günlük satırları eşit;</li>
 *   <li>ayar okumaları: tek ek okuma {@code site.monitor.checks.cert-chunks.enabled} (bellek).</li>
 * </ul>
 * İzin verilen fark (iki kurulumda da kayıttan ÖNCE uygulanır): açılış şema yaması (iki boş tablo). Denetim karşıtı: aynı senaryo
 * anahtar AÇIKKEN (başka canlı pod var) 3-4 ifadelerini gerçekten üretir.
 */
@Timeout(value = 120, unit = TimeUnit.SECONDS)
class CertChunksOffSqlTranscriptTest {

    static final int DOMAINS = 45;   // ≥ min-domains (40): anahtar açık olsaydı parçalı koşardı
    static final String HEARTBEAT_DDL = "CREATE TABLE IF NOT EXISTS system_heartbeat ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recorded_at TIMESTAMP NOT NULL, "
            + "instance_id VARCHAR(120), shutdown_marker BOOLEAN)";
    static final Pattern RUN_ID = Pattern.compile("\\b[0-9a-f]{12}\\b");
    static final Pattern MOCK_HASH = Pattern.compile("hashCode: -?\\d+");
    static final Pattern IDENTITY = Pattern.compile("@[0-9a-f]{4,}");
    /**
     * Bayat süpürmesinin kesim zamanı duvar saatinden gelir ({@code Instant.now() − stale-minutes}, 20.170.0 ile aynı); iki koşu
     * saniye sınırına denk gelirse değer bir saniye farklı olur — yalnız bu bağımsız değişken eşitlenir.
     */
    static final Pattern STALE_CUTOFF = Pattern.compile("findByCheckedAtGreaterThanEqual\\(\"[^\"]*\"\\)");

    record Out(List<String> sql, List<String> mocks, List<String> settingsReads, List<String> logs) {}

    static Out run(boolean withBeans, boolean switchOn) throws Exception {
        try (MultiPodTestSupport mp = MultiPodTestSupport.create()) {
            // Açılış şeması — iki kurulumda da, kayıttan ÖNCE (izin verilen tek fark: boş cert_sweep_* tabloları)
            mp.jdbc().execute(R34CertRig.NETWORK_OUTAGE_DDL);
            mp.jdbc().execute(HEARTBEAT_DDL);
            new ClusterHealthSchemaPatch(mp.jdbc()).apply();
            new CertSweepSchemaPatch(mp.jdbc()).apply();
            // Başka bir CANLI pod (PodLiveness sorulsaydı "evet" derdi)
            mp.jdbc().update("INSERT INTO system_heartbeat(recorded_at, instance_id, shutdown_marker) VALUES (?, ?, ?)",
                    LocalDateTime.ofInstant(Instant.ofEpochMilli(mp.now()), ZoneOffset.UTC), "pod9-00000009", false);

            SqlRecordingDataSource ds = new SqlRecordingDataSource(mp.dataSource());
            JdbcTemplate rec = new JdbcTemplate(ds);

            AppSettingsService settings = mp.mock(AppSettingsService.class);
            when(settings.getBoolean(eq(CertChunking.KEY_ENABLED), anyBoolean())).thenReturn(switchOn);
            EmailNotificationService email = mp.mock(EmailNotificationService.class);
            CertificateInventoryRepository inventory = mp.mock(CertificateInventoryRepository.class);
            when(inventory.findByActiveTrueOrderByDomainAsc()).thenAnswer(i -> inventoryRows());
            LatestCheckRepository latest = mp.mock(LatestCheckRepository.class);
            CertificateCheckerService checker = mock(CertificateCheckerService.class);
            when(checker.checkAsync(anyString(), anyInt(), anyBoolean(), any(), any())).thenAnswer(i -> {
                String d = i.getArgument(0);
                int idx = Integer.parseInt(d.substring(1, 5));
                return CompletableFuture.completedFuture(R34CertRig.defaultResult(idx, d));
            });
            CertificateService certService = mock(CertificateService.class);
            EscalationService escalation = mock(EscalationService.class);
            when(escalation.resolveVerifiedStaleCertAlerts(anyList())).thenReturn(0);
            mp.use(CertificateCheckerService.class, checker);
            mp.use(CertificateService.class, certService);
            mp.use(EscalationService.class, escalation);

            String owner = MultiPodTestSupport.owner(1);
            MultiPodTestSupport.Pod pod = mp.pod(1, s -> {
                ReflectionTestUtils.setField(s, "jdbcTemplate", rec);
                ReflectionTestUtils.setField(s, "clusterSchedule", new ClusterScheduleService(rec, owner));
                ReflectionTestUtils.setField(s, "lockService", new ClusterLockService(rec, owner, mp.clockSupplier(), false));
                CertNetworkOutageService outage = new CertNetworkOutageService(rec, email, settings)
                        .withSystemAdminEmailDefault(R34CertRig.ADMIN);
                ReflectionTestUtils.setField(outage, "clock", mp.clockSupplier());
                ReflectionTestUtils.setField(s, "certNetworkOutage", outage);
                ReflectionTestUtils.setField(s, "clusterHealthStore", new ClusterHealthStore(rec));
                ReflectionTestUtils.setField(s, "systemAdminEmail", R34CertRig.ADMIN);
                ReflectionTestUtils.setField(s, "networkMinErrors", 3);
                ReflectionTestUtils.setField(s, "networkErrorRateThreshold", 0.5);
                ReflectionTestUtils.setField(s, "lockTtlMinutes", 10);
                ReflectionTestUtils.setField(s, "certCheckMaxWaitSeconds", 900L);
                ReflectionTestUtils.setField(s, "hourlyLockWaitMs", 0L);
            });
            SchedulerService ss = pod.scheduler();

            CertChunking cc = null;
            CertChunkWorker worker = null;
            AnchoredDbClock dbClock = null;
            if (withBeans) {
                cc = new CertChunking(settings, CertChunking.Tuning.DEFAULTS);
                dbClock = new AnchoredDbClock(rec);
                JdbcCertSweepStore store = new JdbcCertSweepStore(rec, dbClock);   // Spring kurucusu
                store.markTablesReady(true);                                       // açılış yamasının bildirimi (bellek)
                SchedulerCertChunks runner = new SchedulerCertChunks(R33ClusterRig.provider(SchedulerService.class, ss));
                PodLiveness liveness = new PodLiveness(rec, owner, mp.clockSupplier());
                CertRunCoordinator coordinator = new CertRunCoordinator(cc, R33ClusterRig.provider(CertSweepStore.class, store),
                        R33ClusterRig.provider(CertChunkRunner.class, runner),
                        R33ClusterRig.provider(PodLiveness.class, liveness),
                        R33ClusterRig.provider(DataSource.class, ds));
                worker = new CertChunkWorker(store, cc, R33ClusterRig.provider(CertChunkRunner.class, runner),
                        R33ClusterRig.provider(SchedulerService.class, ss), R33ClusterRig.provider(PodLiveness.class, liveness));
                ReflectionTestUtils.setField(worker, "coordinator", R33ClusterRig.provider(CertRunCoordinator.class, coordinator));
                worker.register();   // @PostConstruct: durum kaynağı + tembel başlatıcı (bellek)
                ReflectionTestUtils.setField(ss, "certRunCoordinator", coordinator);
            }

            ds.clear();
            Map<String, Object> mocks = new TreeMap<>();
            mocks.put("checker", checker);
            mocks.put("certService", certService);
            mocks.put("escalation", escalation);
            mocks.put("inventory", inventory);
            mocks.put("latest", latest);
            mocks.put("email", email);
            Mockito.clearInvocations(mocks.values().toArray());
            Mockito.clearInvocations(settings);

            Logger root = (Logger) LoggerFactory.getLogger("com.sitemonitor");
            Level previous = root.getLevel();
            ListAppender<ILoggingEvent> appender = new ListAppender<>();
            appender.start();
            root.setLevel(Level.INFO);
            root.addAppender(appender);
            try {
                if (cc != null) {
                    cc.onReady(null);   // ApplicationReadyEvent
                    cc.onSettingsChanged(new AppSettingsChangedEvent(Set.of(CertChunking.KEY_ENABLED), "save"));
                    cc.onSettingsChanged(new AppSettingsChangedEvent(Set.of(), "refresh"));
                }
                ss.runCheck();                                                                   // tam tur
                mp.advance(3_600_000L);
                R34CertRig.invoke(ss, "scheduledHourlyCheckNow", new Class<?>[] {String.class}, R34CertRig.CRON);   // saatlik
                mp.advance(600_000L);
                R34CertRig.invoke(ss, "checkStaleInventoryRound", new Class<?>[0]);              // bayat
                if (cc != null) {
                    cc.onSettingsChanged(new AppSettingsChangedEvent(Set.of(CertChunking.KEY_ENABLED), "save"));
                    worker.onContextClosed(null);
                    cc.onContextClosed(null);
                    worker.destroy();
                }
                ss.onContextClosed(null);
            } finally {
                root.detachAppender(appender);
                root.setLevel(previous);
                appender.stop();
                if (worker != null) {
                    worker.onContextClosed(null);
                    worker.destroy();
                }
            }
            List<String> sql = new ArrayList<>(ds.statements());
            sql.sort(Comparator.naturalOrder());
            List<String> logs = new ArrayList<>();
            for (ILoggingEvent e : appender.list) {
                if (e.getLevel().isGreaterOrEqual(Level.INFO)) logs.add(e.getLevel() + " " + e.getLoggerName() + " "
                        + norm(e.getFormattedMessage()));
            }
            if (switchOn && dbClock != null) assertThat(dbClock.anchors()).as("karşı sınama: DB saati çapalandı").isPositive();
            if (!switchOn && dbClock != null) assertThat(dbClock.anchors()).as("anahtar kapalı: DB saati çapalanmadı").isZero();
            return new Out(sql, transcript(mocks), settingsReads(settings), logs);
        }
    }

    static List<CertificateInventory> inventoryRows() {
        List<CertificateInventory> out = new ArrayList<>();
        for (int i = 0; i < DOMAINS; i++) {
            CertificateInventory c = new CertificateInventory();
            c.setId((long) i + 1);
            c.setDomain(R34CertRig.domain(i));
            c.setPort(i % 9 == 4 ? 8443 : 443);
            c.setUseProxy(i % 7 == 3);
            c.setTlsMode(i % 5 == 1 ? "browser" : null);
            c.setTimeoutSeconds(i % 11 == 6 ? 15 : null);
            c.setActive(true);
            out.add(c);
        }
        return out;
    }

    static String norm(String s) {
        String out = RUN_ID.matcher(s).replaceAll("<run>");
        out = MOCK_HASH.matcher(out).replaceAll("hashCode: #");
        return IDENTITY.matcher(out).replaceAll("@#");
    }

    /** Sıralı döküm: {@code ad.yöntem(arg, …)} — Mockito'nun genel sıra numarasıyla. */
    static List<String> transcript(Map<String, Object> mocks) {
        List<Invocation> all = new ArrayList<>();
        Map<Invocation, String> owner = new HashMap<>();
        for (Map.Entry<String, Object> e : mocks.entrySet()) {
            for (Invocation inv : Mockito.mockingDetails(e.getValue()).getInvocations()) {
                all.add(inv);
                owner.put(inv, e.getKey());
            }
        }
        all.sort(Comparator.comparingInt(Invocation::getSequenceNumber));
        List<String> out = new ArrayList<>();
        for (Invocation inv : all) {
            List<String> args = new ArrayList<>();
            for (Object a : inv.getArguments()) args.add(norm(R34CertRig.canon(a, Set.of())));
            String call = owner.get(inv) + "." + inv.getMethod().getName() + "(" + String.join(", ", args) + ")";
            out.add(STALE_CUTOFF.matcher(call).replaceAll("findByCheckedAtGreaterThanEqual(\"<cutoff>\")"));
        }
        return out;
    }

    static List<String> settingsReads(AppSettingsService settings) {
        List<String> out = new ArrayList<>();
        for (Invocation inv : Mockito.mockingDetails(settings).getInvocations()) {
            Object[] a = inv.getArguments();
            out.add(inv.getMethod().getName() + "(" + (a.length > 0 ? a[0] : "") + ")");
        }
        out.sort(Comparator.naturalOrder());
        return out;
    }

    @Test
    @DisplayName("L-1: anahtar KAPALI + tüm 3-4 parçaları — tam / saatlik / bayat turlar ve olaylar 3-4'süz kurulumla AYNI SQL "
            + "çoklu kümesi, AYNI bağımlılık dökümü, AYNI günlük; 3-4 tablosu / PodLiveness / DB saati / yayın kuruluşu ifadesi yok, "
            + "tek ek ayar okuması anahtarın kendisi")
    void offWithBeans_identicalToNoBeans() throws Exception {
        Out bare = run(false, false);
        Out off = run(true, false);

        assertThat(bare.sql()).as("ifade koştu (test kör değil)").isNotEmpty()
                .anyMatch(q -> q.contains("scheduler_lock")).anyMatch(q -> q.contains("network_outage_events"))
                .anyMatch(q -> q.contains("scan_runs")).anyMatch(q -> q.contains("monitor_check_schedule"));
        assertThat(off.sql()).as("SQL çoklu kümesi birebir").containsExactlyElementsOf(bare.sql());
        assertThat(off.sql()).as("anahtar kapalı: 3-4 tablosu, PodLiveness, DB saati, yayın kuruluşu okuması yok")
                .noneMatch(q -> q.contains("cert_sweep") || q.contains("system_heartbeat") || q.contains("issuer_dn")
                        || q.contains("CURRENT_TIMESTAMP") || q.contains("clock_timestamp"));

        assertThat(bare.mocks()).as("döküm dolu").hasSizeGreaterThan(3 * DOMAINS);
        assertThat(String.join("\n", bare.mocks())).contains("certService.saveResult", "escalation.processResults",
                "checker.checkAsync", "certService.evictAllCaches");
        assertThat(off.mocks()).as("bağımlılık çağrıları birebir").containsExactlyElementsOf(bare.mocks());
        assertThat(off.logs()).as("günlük satırları birebir").containsExactlyElementsOf(bare.logs());

        List<String> extra = new ArrayList<>(off.settingsReads());
        for (String r : bare.settingsReads()) extra.remove(r);
        assertThat(extra).as("ek ayar okumaları YALNIZ anahtar (bellek)").isNotEmpty()
                .allMatch(r -> r.equals("getBoolean(" + CertChunking.KEY_ENABLED + ")"));
        List<String> missing = new ArrayList<>(bare.settingsReads());
        for (String r : off.settingsReads()) missing.remove(r);
        assertThat(missing).isEmpty();
    }

    @Test
    @DisplayName("Denetim karşıtı: aynı senaryo anahtar AÇIKKEN (başka canlı pod var) 3-4 ifadelerini üretir — cert_sweep_*, "
            + "PodLiveness, yayın kuruluşu okuması, DB saati")
    void switchOn_producesCertSweepStatements() throws Exception {
        Out on = run(true, true);
        assertThat(on.sql()).anyMatch(q -> q.contains("cert_sweep_runs")).anyMatch(q -> q.contains("cert_sweep_chunks"))
                .anyMatch(q -> q.contains("system_heartbeat")).anyMatch(q -> q.contains("issuer_dn"))
                .anyMatch(q -> q.contains("CURRENT_TIMESTAMP"));
        assertThat(String.join("\n", on.logs())).contains("Sertifika taraması parçalı");
    }
}
