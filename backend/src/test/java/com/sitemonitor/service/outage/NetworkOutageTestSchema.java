package com.sitemonitor.service.outage;

import com.sitemonitor.service.AppSettingsService;
import org.mockito.Mockito;
import org.springframework.jdbc.core.JdbcTemplate;

/** Ağ kesintisi testleri için ortak H2 şeması + varsayılanı dönen ayar sahtesi (2026-10-21, çok pod). */
final class NetworkOutageTestSchema {

    private NetworkOutageTestSchema() {}

    /** {@code network_outage_events} — varlığın (NetworkOutageEvent) H2 karşılığı, posta sütunları dâhil. */
    static final String DDL = "CREATE TABLE IF NOT EXISTS network_outage_events ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "detected_at VARCHAR(255) NOT NULL, resolved_at VARCHAR(255), "
            + "network_errors INTEGER, total_checks INTEGER, error_rate DOUBLE PRECISION, threshold DOUBLE PRECISION, "
            + "duration_ms BIGINT, status VARCHAR(16) NOT NULL, source VARCHAR(32), "
            + "alert_mail_status VARCHAR(255), alert_mail_claimed_ms BIGINT, alert_mail_attempts INTEGER, "
            + "resolved_mail_status VARCHAR(255), resolved_mail_claimed_ms BIGINT, resolved_mail_attempts INTEGER, "
            + "last_confirmed_at VARCHAR(30))";

    /** Sütunlardan ÖNCEKİ şema (eski sürüm) — şema yaması testi. */
    static final String LEGACY_DDL = "CREATE TABLE IF NOT EXISTS network_outage_events ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "detected_at VARCHAR(255) NOT NULL, resolved_at VARCHAR(255), "
            + "network_errors INTEGER, total_checks INTEGER, error_rate DOUBLE PRECISION, threshold DOUBLE PRECISION, "
            + "duration_ms BIGINT, status VARCHAR(16) NOT NULL, source VARCHAR(32))";

    static void create(JdbcTemplate jdbc) {
        jdbc.execute(DDL);
    }

    /** {@code getX(key, varsayılan)} → varsayılan. */
    static AppSettingsService defaultSettings() {
        return Mockito.mock(AppSettingsService.class, Mockito.withSettings().defaultAnswer(inv -> {
            Object[] a = inv.getArguments();
            if (inv.getMethod().getName().startsWith("get") && a.length == 2 && a[0] instanceof String) return a[1];
            return Mockito.RETURNS_DEFAULTS.answer(inv);
        }));
    }

    /** Eski sürüm pod'unun yazdığı satır (posta sütunları NULL). */
    static long insertLegacyOngoing(JdbcTemplate jdbc, String source, String detectedAt) {
        jdbc.update("INSERT INTO network_outage_events (detected_at, network_errors, total_checks, error_rate, threshold, "
                + "status, source) VALUES (?, 5, 10, 0.5, 0.5, 'ONGOING', ?)", detectedAt, source);
        return jdbc.queryForObject("SELECT MAX(id) FROM network_outage_events", Long.class);
    }
}
