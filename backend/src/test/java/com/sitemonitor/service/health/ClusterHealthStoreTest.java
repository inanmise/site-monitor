package com.sitemonitor.service.health;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.Map;
import java.util.concurrent.atomic.AtomicInteger;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Sistem Sağlığı küme deposu + şema yaması (2026-10-23, çok pod R2b, MP-34 / MP-35 / N4) — H2 (PostgreSQL kipi):
 * tablolar ve heartbeat kolonları idempotent kurulur; tarama satırı koşullu yazılır (eski sonuç yeniyi ezmez, düşen tur
 * son başarılı sayıları korur, temiz tur hatayı siler); gözlem yalnız daha yeniyse yazılır; tablo yokken yazma
 * fırlatmaz, okuma fırlatır (çağıran "local"a düşer).
 */
class ClusterHealthStoreTest {

    private static final AtomicInteger SEQ = new AtomicInteger();
    JdbcTemplate jdbc;
    ClusterHealthStore store;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:clusterhealth" + SEQ.incrementAndGet() + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE"));
        jdbc.execute("CREATE TABLE system_heartbeat (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recorded_at TIMESTAMP NOT NULL)");
        store = new ClusterHealthStore(jdbc);
    }

    @AfterEach
    void tearDown() {
        jdbc.execute("SHUTDOWN");
    }

    @Test
    @DisplayName("şema yaması: iki tablo + iki heartbeat kolonu; ikinci koşu değişiklik yapmaz")
    void schemaPatchIsIdempotent() {
        ClusterHealthSchemaPatch patch = new ClusterHealthSchemaPatch(jdbc);
        assertThat(patch.apply()).isEqualTo(4);
        assertThat(patch.apply()).isZero();
        assertThat(patch.tableReadable("scan_runs")).isTrue();
        assertThat(patch.tableReadable("cluster_observations")).isTrue();
        assertThat(patch.columnReadable("system_heartbeat", "instance_id")).isTrue();
        assertThat(patch.columnReadable("system_heartbeat", "shutdown_marker")).isTrue();
    }

    @Test
    @DisplayName("şema yaması: heartbeat tablosu yoksa kolonlar atlanır (ddl-auto kuracak), tablolar kurulur")
    void schemaPatchWithoutHeartbeatTable() {
        jdbc.execute("DROP TABLE system_heartbeat");
        assertThat(new ClusterHealthSchemaPatch(jdbc).apply()).isEqualTo(2);
    }

    @Test
    @DisplayName("tarama satırı: ekle → güncelle; eski tur yeniyi ezmez; düşen tur sayıları korur; temiz tur hatayı siler")
    void scanRunRules() {
        new ClusterHealthSchemaPatch(jdbc).apply();
        assertThat(store.recordScanRun("hourly", "r1", "pod1-00000001", "2026-10-21T06:00:00", 1200L, 10, 1, 0, null)).isTrue();
        assertThat(store.recordScanRun("hourly", "r2", "pod2-00000002", "2026-10-21T07:00:00", 900L, 11, 0, 2, null)).isTrue();
        // geç yazan eski tur (06:30) → daha yeni satırı ezmez
        assertThat(store.recordScanRun("hourly", "r0", "pod3-00000003", "2026-10-21T06:30:00", 5L, 1, 0, 0, null)).isFalse();
        ClusterHealthStore.ScanRun r = store.readScanRuns().get("hourly");
        assertThat(r.runId()).isEqualTo("r2");
        assertThat(r.instanceId()).isEqualTo("pod2-00000002");
        assertThat(r.total()).isEqualTo(11);
        assertThat(r.lastRunAt()).isEqualTo("2026-10-21T07:00:00");

        // sonuç kaydedemeden düşen tur: hata alanları; son başarılı koşu, pod'u ve sayıları korunur
        assertThat(store.recordScanRun("hourly", "r3", "pod1-00000001", "2026-10-21T08:00:00", null, null, null, null, "db down")).isTrue();
        r = store.readScanRuns().get("hourly");
        assertThat(r.failure()).isEqualTo("db down");
        assertThat(r.failureAt()).isEqualTo("2026-10-21T08:00:00");
        assertThat(r.failureBy()).isEqualTo("pod1-00000001");
        assertThat(r.runId()).isEqualTo("r2");
        assertThat(r.instanceId()).isEqualTo("pod2-00000002");
        assertThat(r.total()).isEqualTo(11);
        assertThat(r.updatedAt()).isEqualTo("2026-10-21T08:00:00");

        // temiz tur hatayı siler
        assertThat(store.recordScanRun("hourly", "r4", "pod2-00000002", "2026-10-21T09:00:00", 800L, 12, 0, 0, null)).isTrue();
        r = store.readScanRuns().get("hourly");
        assertThat(r.failure()).isNull();
        assertThat(r.failureAt()).isNull();
        assertThat(r.total()).isEqualTo(12);
    }

    @Test
    @DisplayName("tarama satırı: türler ayrı (bayat tur saatlik satırı ezmez); ilk koşu düşerse satır yalnız hatayla")
    void scanRunKindsAreSeparate() {
        new ClusterHealthSchemaPatch(jdbc).apply();
        store.recordScanRun("hourly", "r1", "pod1-00000001", "2026-10-21T06:00:00", 1200L, 500, 3, 1, null);
        store.recordScanRun("stale", "r2", "pod2-00000002", "2026-10-21T06:05:00", 40L, 3, 0, 0, null);
        store.recordScanRun("full", "r3", "pod1-00000001", "2026-10-21T06:06:00", null, null, null, null, "boom");
        Map<String, ClusterHealthStore.ScanRun> runs = store.readScanRuns();
        assertThat(runs).containsOnlyKeys("hourly", "stale", "full");
        assertThat(runs.get("hourly").total()).isEqualTo(500);
        assertThat(runs.get("stale").total()).isEqualTo(3);
        assertThat(runs.get("full").lastRunAt()).isNull();
        assertThat(runs.get("full").failure()).isEqualTo("boom");
    }

    @Test
    @DisplayName("tablo yok: yazma fırlatmaz (false / FAILED), okuma fırlatır")
    void missingTables() {
        assertThat(store.recordScanRun("hourly", "r", "p", "2026-10-21T06:00:00", 1L, 1, 0, 0, null)).isFalse();
        assertThat(store.publish("rdap-source", "p", 1L, "{}", "2026-10-21T06:00:00")).isEqualTo(ClusterHealthStore.Publish.FAILED);
        assertThatThrownBy(() -> store.readScanRuns()).isInstanceOf(RuntimeException.class);
        assertThatThrownBy(() -> store.read("rdap-source")).isInstanceOf(RuntimeException.class);
    }

    @Test
    @DisplayName("gözlem: yalnız daha yeni yazılır; eşit / eski NOT_NEWER; okuma son hâli")
    void observationNewestWins() {
        new ClusterHealthSchemaPatch(jdbc).apply();
        assertThat(store.read("rdap-source")).isEmpty();
        assertThat(store.publish("rdap-source", "pod1-00000001", 1_000L, "{\"source\":\"NONE\"}", "t1")).isEqualTo(ClusterHealthStore.Publish.WRITTEN);
        assertThat(store.publish("rdap-source", "pod2-00000002", 900L, "{\"source\":\"RDAP\"}", "t2")).isEqualTo(ClusterHealthStore.Publish.NOT_NEWER);
        assertThat(store.publish("rdap-source", "pod2-00000002", 1_000L, "{\"source\":\"RDAP\"}", "t2")).isEqualTo(ClusterHealthStore.Publish.NOT_NEWER);
        assertThat(store.read("rdap-source").orElseThrow().instanceId()).isEqualTo("pod1-00000001");
        assertThat(store.publish("rdap-source", "pod2-00000002", 2_000L, "{\"source\":\"RDAP\"}", "t3")).isEqualTo(ClusterHealthStore.Publish.WRITTEN);
        ClusterHealthStore.Observation o = store.read("rdap-source").orElseThrow();
        assertThat(o.instanceId()).isEqualTo("pod2-00000002");
        assertThat(o.observedMs()).isEqualTo(2_000L);
        assertThat(o.payload()).contains("RDAP");
    }

    @Test
    @DisplayName("podOf: <host>-<8 onaltılık> son eki atılır; biçim dışı kimlik olduğu gibi")
    void podOfTruthTable() {
        assertThat(ClusterHealthStore.podOf("site-monitor-7d9f6c-x2k4p-1a2b3c4d")).isEqualTo("site-monitor-7d9f6c-x2k4p");
        assertThat(ClusterHealthStore.podOf("pod1-00000001")).isEqualTo("pod1");
        assertThat(ClusterHealthStore.podOf("host-xyz")).isEqualTo("host-xyz");
        assertThat(ClusterHealthStore.podOf("host-1234567g")).isEqualTo("host-1234567g");
        assertThat(ClusterHealthStore.podOf("12345678")).isEqualTo("12345678");
        assertThat(ClusterHealthStore.podOf(null)).isNull();
    }

    @Test
    @DisplayName("uzun hata metni sütuna kırpılır (… ile)")
    void longFailureIsClipped() {
        new ClusterHealthSchemaPatch(jdbc).apply();
        store.recordScanRun("hourly", "r", "p", "2026-10-21T06:00:00", null, null, null, null, "x".repeat(900));
        String f = store.readScanRuns().get("hourly").failure();
        assertThat(f).hasSize(ClusterHealthStore.FAILURE_MAX).endsWith("…");
    }
}
