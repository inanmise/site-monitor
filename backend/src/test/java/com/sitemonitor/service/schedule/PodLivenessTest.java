package com.sitemonitor.service.schedule;

import com.sitemonitor.service.ExtendedHealthService;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.Optional;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicLong;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * R3-1 3e (2026-10-23): "başka canlı pod var mı?" — R2b heartbeat satırlarının "canlı" kuralı ({@code podStates}): bu pod
 * hariç, kapanış işareti yok, son heartbeat ≥ şimdi − 3 dk, NULL {@code instance_id} (20.166.0) sayılmaz; 30 sn önbellek;
 * okunamazsa bilinmiyor (= erteleme yok), hiç fırlatmaz.
 */
class PodLivenessTest {

    private static final AtomicInteger SEQ = new AtomicInteger();
    private static final long T0 = Instant.parse("2026-10-23T07:00:00Z").toEpochMilli();

    JdbcTemplate jdbc;
    final AtomicLong clock = new AtomicLong(T0);

    @BeforeEach
    void db() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:podliveness" + SEQ.incrementAndGet()
                + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE"));
        jdbc.execute(HEARTBEAT_DDL);
    }

    @AfterEach
    void close() {
        jdbc.execute("SHUTDOWN");
    }

    /** Üretimdeki {@code system_heartbeat} kolonları (entity {@code SystemHeartbeat}). */
    static final String HEARTBEAT_DDL = "CREATE TABLE IF NOT EXISTS system_heartbeat ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recorded_at TIMESTAMP NOT NULL, "
            + "instance_id VARCHAR(120), shutdown_marker BOOLEAN)";

    void beat(String instance, long atMs, Boolean marker) {
        jdbc.update("INSERT INTO system_heartbeat(recorded_at, instance_id, shutdown_marker) VALUES (?, ?, ?)",
                LocalDateTime.ofInstant(Instant.ofEpochMilli(atMs), ZoneOffset.UTC), instance, marker);
    }

    PodLiveness liveness(String self) {
        return new PodLiveness(jdbc, self, clock::get);
    }

    @Test
    @DisplayName("Kendi satırı sayılmaz; başka pod'un taze heartbeat'i canlı")
    void selfExcluded_otherLive() {
        beat("me-1", T0 - 30_000, null);
        PodLiveness l = liveness("me-1");
        assertThat(l.otherLivePods()).contains(0);
        assertThat(l.anotherLivePod()).isFalse();

        beat("other-2", T0 - 30_000, null);
        l.invalidate();
        assertThat(l.otherLivePods()).contains(1);
        assertThat(l.anotherLivePod()).isTrue();
        assertThat(l.cachedOtherPods()).containsExactly("other-2");
    }

    @Test
    @DisplayName("Kapanış işareti = canlı değil (dağıtım / ölçekleme)")
    void shutdownMarkerIsNotLive() {
        beat("other-2", T0 - 90_000, null);
        beat("other-2", T0 - 20_000, Boolean.TRUE);
        assertThat(liveness("me-1").anotherLivePod()).isFalse();
    }

    @Test
    @DisplayName("3 dk sınırı: tam 3 dk önceki heartbeat canlı, 3 dk + 1 sn önceki değil")
    void threeMinuteEdge() {
        assertThat(ExtendedHealthService.POD_LIVE_MINUTES).as("Sistem Sağlığı pod listesiyle aynı kural").isEqualTo(3);
        beat("edge-2", T0 - 3 * 60_000L, null);
        assertThat(liveness("me-1").anotherLivePod()).as("tam sınır canlı").isTrue();

        jdbc.update("DELETE FROM system_heartbeat");
        beat("old-3", T0 - 3 * 60_000L - 1_000L, null);
        assertThat(liveness("me-1").anotherLivePod()).as("sınırın 1 sn ötesi sessiz").isFalse();
    }

    @Test
    @DisplayName("FX-SIDE #3: aynı POD ADININ başka kimliği (kirli yeniden başlatmadan önceki süreç, işaretsiz taze heartbeat) "
            + "sayılmaz; başka pod adı sayılır")
    void samePodNameOtherProcessNotCounted() {
        beat("site-monitor-7d9f-x2k4p-0a1b2c3d", T0 - 20_000, null);   // aynı pod, önceki süreç (OOM / SIGKILL — işaret yok)
        PodLiveness l = liveness("site-monitor-7d9f-x2k4p-9f8e7d6c");
        assertThat(l.otherLivePods()).as("tek pod'un kendi önceki süreci 'başka canlı pod' değil").contains(0);
        assertThat(l.anotherLivePod()).isFalse();

        beat("site-monitor-7d9f-b7q2m-11223344", T0 - 20_000, null);   // gerçekten başka pod
        l.invalidate();
        assertThat(l.otherLivePods()).contains(1);
        assertThat(l.cachedOtherPods()).containsExactly("site-monitor-7d9f-b7q2m-11223344");
    }

    @Test
    @DisplayName("NULL instance_id (20.166.0 pod'u) sayılmaz")
    void nullInstanceIgnored() {
        beat(null, T0 - 10_000, null);
        assertThat(liveness("me-1").otherLivePods()).contains(0);
    }

    @Test
    @DisplayName("Karar 30 sn önbellekte: yeni heartbeat süre dolana dek görünmez; sonra görünür")
    void cachedThirtySeconds() {
        PodLiveness l = liveness("me-1");
        assertThat(l.anotherLivePod()).isFalse();
        beat("other-2", T0, null);
        clock.addAndGet(PodLiveness.CACHE_MS - 1);
        assertThat(l.anotherLivePod()).as("önbellekten").isFalse();
        assertThat(l.cachedAnotherLivePod()).isFalse();
        clock.addAndGet(1);
        assertThat(l.anotherLivePod()).as("süre doldu, yeniden okundu").isTrue();
        assertThat(l.cachedAnotherLivePod()).isTrue();
        clock.addAndGet(2 * PodLiveness.CACHE_MS + 1);
        assertThat(l.cachedAnotherLivePod()).as("eski önbellek = bilinmiyor (durum satırı)").isNull();
    }

    @Test
    @DisplayName("Okunamazsa (tablo yok) bilinmiyor → 'başka canlı pod yok' (erteleme yapılmaz); fırlatmaz; bilinmeyen de önbellekte")
    void unreadableIsUnknown() {
        jdbc.execute("DROP TABLE system_heartbeat");
        PodLiveness l = liveness("me-1");
        assertThat(l.otherLivePods()).isEqualTo(Optional.empty());
        assertThat(l.anotherLivePod()).isFalse();
        assertThat(l.cachedAnotherLivePod()).isNull();

        jdbc.execute(HEARTBEAT_DDL);
        beat("other-2", T0, null);
        assertThat(l.otherLivePods()).as("bilinmeyen sonuç da 30 sn tutulur — her tıkta sorgu yok").isEmpty();
        clock.addAndGet(PodLiveness.CACHE_MS);
        assertThat(l.anotherLivePod()).isTrue();
    }
}
