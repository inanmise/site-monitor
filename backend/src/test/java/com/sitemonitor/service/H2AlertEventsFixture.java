/**
 * Çok pod alarm testleri için H2'ye bağlı {@link AlertEventRepository} sahtesi (2026-10-21, çok pod R1 / C2). İki
 * {@code EscalationService} örneği AYNI tabloyu görür; sahiplenmeler ({@code JdbcTemplate}) ile depo okumaları aynı
 * satırları okur/yazar. Varlık kaydı üretimdeki gibi {@code resolution_notify*} kolonlarını YAZMAZ (salt okunur kolonlar).
 * Yalnız {@code EscalationService}'in bu testlerde kullandığı yöntemler bağlanır; gerisi Mockito varsayılanı.
 */
final class H2AlertEventsFixture {

    static final String DDL = "CREATE TABLE IF NOT EXISTS alert_events ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "domain VARCHAR(255) NOT NULL, alert_level VARCHAR(16) NOT NULL, alert_type VARCHAR(64) NOT NULL, "
            + "message VARCHAR(4000), days_remaining INT, not_after VARCHAR(40), team_id BIGINT, "
            + "notified_contacts VARCHAR(4000), context_json VARCHAR(4000), acknowledged BOOLEAN DEFAULT FALSE, "
            + "resolved BOOLEAN NOT NULL DEFAULT FALSE, resolved_at VARCHAR(40), resolved_by VARCHAR(255), "
            + "created_at VARCHAR(40), last_re_alert_at VARCHAR(40), realert_count INT, storm_id BIGINT, "
            + "notification_group_id BIGINT, resolution_notify VARCHAR(16), resolution_notify_at VARCHAR(30))";

    private static final String COLS = "id, domain, alert_level, alert_type, message, days_remaining, not_after, team_id, "
            + "notified_contacts, context_json, acknowledged, resolved, resolved_at, resolved_by, created_at, last_re_alert_at, "
            + "realert_count, storm_id, notification_group_id, resolution_notify, resolution_notify_at";

    private static final RowMapper<AlertEvent> MAPPER = (rs, i) -> {
        AlertEvent e = new AlertEvent();
        e.setId(rs.getLong("id"));
        e.setDomain(rs.getString("domain"));
        e.setAlertLevel(rs.getString("alert_level"));
        e.setAlertType(rs.getString("alert_type"));
        e.setMessage(rs.getString("message"));
        int d = rs.getInt("days_remaining");
        e.setDaysRemaining(rs.wasNull() ? null : d);
        e.setNotAfter(rs.getString("not_after"));
        long t = rs.getLong("team_id");
        e.setTeamId(rs.wasNull() ? null : t);
        e.setNotifiedContacts(rs.getString("notified_contacts"));
        e.setContextJson(rs.getString("context_json"));
        e.setAcknowledged(rs.getBoolean("acknowledged"));
        e.setResolved(rs.getBoolean("resolved"));
        e.setResolvedAt(rs.getString("resolved_at"));
        e.setResolvedBy(rs.getString("resolved_by"));
        e.setCreatedAt(rs.getString("created_at"));
        e.setLastReAlertAt(rs.getString("last_re_alert_at"));
        int rc = rs.getInt("realert_count");
        e.setRealertCount(rs.wasNull() ? 0 : rc);
        long s = rs.getLong("storm_id");
        e.setStormId(rs.wasNull() ? null : s);
        long g = rs.getLong("notification_group_id");
        e.setNotificationGroupId(rs.wasNull() ? null : g);
        e.setResolutionNotify(rs.getString("resolution_notify"));
        e.setResolutionNotifyAt(rs.getString("resolution_notify_at"));
        return e;
    };

    private final JdbcTemplate jdbc;
    private final AlertEventRepository repo;

    H2AlertEventsFixture(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
        jdbc.execute(DDL);
        this.repo = mock(AlertEventRepository.class);
        bind();
    }

    AlertEventRepository repo() {
        return repo;
    }

    JdbcTemplate jdbc() {
        return jdbc;
    }

    List<AlertEvent> all() {
        return jdbc.query("SELECT " + COLS + " FROM alert_events ORDER BY id", MAPPER);
    }

    Optional<AlertEvent> byId(Long id) {
        return jdbc.query("SELECT " + COLS + " FROM alert_events WHERE id = ?", MAPPER, id).stream().findFirst();
    }

    synchronized AlertEvent save(AlertEvent e) {
        if (e.getId() == null) {
            KeyHolder kh = new GeneratedKeyHolder();
            jdbc.update(con -> {
                PreparedStatement ps = con.prepareStatement("INSERT INTO alert_events(domain, alert_level, alert_type, message, "
                        + "days_remaining, not_after, team_id, notified_contacts, context_json, acknowledged, resolved, resolved_at, "
                        + "resolved_by, created_at, last_re_alert_at, realert_count, storm_id, notification_group_id) "
                        + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", Statement.RETURN_GENERATED_KEYS);
                bindCommon(ps, e);
                return ps;
            }, kh);
            e.setId(kh.getKey().longValue());
        } else {
            jdbc.update("UPDATE alert_events SET domain = ?, alert_level = ?, alert_type = ?, message = ?, days_remaining = ?, "
                    + "not_after = ?, team_id = ?, notified_contacts = ?, context_json = ?, acknowledged = ?, resolved = ?, "
                    + "resolved_at = ?, resolved_by = ?, created_at = ?, last_re_alert_at = ?, realert_count = ?, storm_id = ?, "
                    + "notification_group_id = ? WHERE id = ?",
                    e.getDomain(), e.getAlertLevel(), e.getAlertType(), e.getMessage(), e.getDaysRemaining(), e.getNotAfter(),
                    e.getTeamId(), e.getNotifiedContacts(), e.getContextJson(), Boolean.TRUE.equals(e.getAcknowledged()),
                    Boolean.TRUE.equals(e.getResolved()), e.getResolvedAt(), e.getResolvedBy(), e.getCreatedAt(),
                    e.getLastReAlertAt(), e.getRealertCount(), e.getStormId(), e.getNotificationGroupId(), e.getId());
        }
        return e;
    }

    private static void bindCommon(PreparedStatement ps, AlertEvent e) throws java.sql.SQLException {
        ps.setString(1, e.getDomain());
        ps.setString(2, e.getAlertLevel());
        ps.setString(3, e.getAlertType());
        ps.setString(4, e.getMessage());
        ps.setObject(5, e.getDaysRemaining());
        ps.setString(6, e.getNotAfter());
        ps.setObject(7, e.getTeamId());
        ps.setString(8, e.getNotifiedContacts());
        ps.setString(9, e.getContextJson());
        ps.setBoolean(10, Boolean.TRUE.equals(e.getAcknowledged()));
        ps.setBoolean(11, Boolean.TRUE.equals(e.getResolved()));
        ps.setString(12, e.getResolvedAt());
        ps.setString(13, e.getResolvedBy());
        ps.setString(14, e.getCreatedAt());
        ps.setString(15, e.getLastReAlertAt());
        ps.setObject(16, e.getRealertCount());
        ps.setObject(17, e.getStormId());
        ps.setObject(18, e.getNotificationGroupId());
    }

    private void bind() {
        lenient().when(repo.save(any(AlertEvent.class))).thenAnswer(inv -> save(inv.getArgument(0)));
        lenient().when(repo.findById(anyLong())).thenAnswer(inv -> byId(inv.getArgument(0)));
        lenient().when(repo.findOpenAlert(anyString(), anyString())).thenAnswer(inv -> jdbc.query(
                "SELECT " + COLS + " FROM alert_events WHERE domain = ? AND alert_type = ? AND resolved = FALSE "
                        + "ORDER BY created_at DESC, id DESC", MAPPER, inv.getArgument(0), inv.getArgument(1)).stream().findFirst());
        lenient().when(repo.findOpenAlerts(anyString(), anyString())).thenAnswer(inv -> jdbc.query(
                "SELECT " + COLS + " FROM alert_events WHERE domain = ? AND alert_type = ? AND resolved = FALSE "
                        + "ORDER BY created_at DESC, id DESC", MAPPER, inv.getArgument(0), inv.getArgument(1)));
        lenient().when(repo.findOpenByDomainIn(anyCollection())).thenAnswer(inv -> {
            Collection<String> d = inv.getArgument(0);
            return all().stream().filter(e -> !Boolean.TRUE.equals(e.getResolved()) && d.contains(e.getDomain())).toList();
        });
        lenient().when(repo.findByDomainAndAlertTypeInAndResolvedFalse(anyString(), anyCollection())).thenAnswer(inv -> {
            String domain = inv.getArgument(0);
            Collection<String> types = inv.getArgument(1);
            return all().stream().filter(e -> !Boolean.TRUE.equals(e.getResolved()) && domain.equals(e.getDomain())
                    && types.contains(e.getAlertType())).toList();
        });
        lenient().when(repo.findByResolvedFalseAndAcknowledgedFalseOrderByCreatedAtDesc()).thenAnswer(inv -> all().stream()
                .filter(e -> !Boolean.TRUE.equals(e.getResolved()) && !Boolean.TRUE.equals(e.getAcknowledged()))
                .sorted((a, b) -> String.valueOf(b.getCreatedAt()).compareTo(String.valueOf(a.getCreatedAt()))).toList());
        lenient().when(repo.markResolvedIfOpen(anyLong(), anyString(), anyString())).thenAnswer(inv -> jdbc.update(
                "UPDATE alert_events SET resolved = TRUE, resolved_at = ?, resolved_by = ? WHERE id = ? AND resolved = FALSE",
                inv.getArgument(1), inv.getArgument(2), inv.getArgument(0)));
        lenient().when(repo.stampNotificationSentIfOpen(anyLong(), anyString(), nullable(Integer.class), nullable(Integer.class),
                nullable(String.class), nullable(String.class))).thenAnswer(inv -> jdbc.update(
                "UPDATE alert_events SET last_re_alert_at = ?, realert_count = ?, days_remaining = ?, not_after = ?, "
                        + "notified_contacts = ? WHERE id = ? AND resolved = FALSE",
                inv.getArgument(1), inv.getArgument(2), inv.getArgument(3), inv.getArgument(4), inv.getArgument(5),
                inv.getArgument(0)));
    }
}
