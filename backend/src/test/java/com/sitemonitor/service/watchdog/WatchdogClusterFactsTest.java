    /** Bir pod örneği: {@code minutesAgo} dakika önce (POD saatiyle yazılmış: gerçek an + fark). */
    void sample(String inst, String pod, long trueMinutesAgo, Long skewMs, Integer pending, Integer active, Integer max) {
        long podClockMs = NOW.minus(Duration.ofMinutes(trueMinutesAgo)).toEpochMilli() + (skewMs == null ? 0 : skewMs);
        String at = WatchdogTransition.ISO.format(Instant.ofEpochMilli(podClockMs).truncatedTo(ChronoUnit.MINUTES));
        mp.jdbc().update("INSERT INTO system_metric_samples(instance_id, pod_name, sampled_at, db_pending, db_active, db_max, "
                + "clock_skew_ms) VALUES (?,?,?,?,?,?,?)", inst, pod, at, pending, active, max, skewMs);
    }

    /** Kapanış işareti — örnekler gibi POD saatiyle yazılır. */
    void marker(String inst, String pod, long trueMinutesAgo, long skewMs) {
        long podClockMs = NOW.minus(Duration.ofMinutes(trueMinutesAgo)).toEpochMilli() + skewMs;
        String at = WatchdogTransition.ISO.format(Instant.ofEpochMilli(podClockMs).truncatedTo(ChronoUnit.MINUTES));
        mp.jdbc().update("INSERT INTO system_metric_samples(instance_id, pod_name, sampled_at, shutdown_marker) VALUES (?,?,?,TRUE)",
                inst, pod, at);
    }

    static DatabaseHealthService.Snapshot snapshot(String connection, String query, String writable, String pool, int schemaFailed) {
        Map<String, Object> checks = new LinkedHashMap<>();
        checks.put("connection", Map.of("status", connection));
        checks.put("query", Map.of("status", query));
        checks.put("writable", Map.of("status", writable));
        checks.put("pool", Map.of("status", pool));
        checks.put("schema", Map.of("status", schemaFailed > 0 ? "DEGRADED" : "UP", "failed_patches", schemaFailed));
        String overall = List.of(connection, query, writable, pool, schemaFailed > 0 ? "DEGRADED" : "UP").contains("DOWN") ? "DOWN"
                : List.of(connection, query, writable, pool, schemaFailed > 0 ? "DEGRADED" : "UP").contains("DEGRADED") ? "DEGRADED" : "UP";
        return new DatabaseHealthService.Snapshot(Map.of("status", overall, "checks", checks), overall, 0L);
    }

    // ── Canlı pod kümesi ─────────────────────────────────────────────────────────────────────

    @Test
    @DisplayName("canlı pod'lar: kapanış işaretli ve sessiz pod hariç; saati 10 dk geri pod düzeltmeyle canlı; aynı adlı iki süreç ayrılır")
    void livePodsAreDerivedFromSamples() {
        sample("pod-a-1111", "pod-a", 1, 400L, 0, 3, 30);
        sample("pod-b-2222", "pod-b", 0, -1_200L, 0, 2, 30);
        sample("pod-c-3333", "pod-c", 1, 90_000L, 0, 2, 30);
        marker("pod-c-3333", "pod-c", 1, 90_000L);                          // durdu (dağıtım) — saat farkı karara girmez
        sample("pod-d-4444", "pod-d", 12, 0L, 0, 2, 30);           // sessiz (çöküş) — son örneği eski
        sample("pod-e-5555", "pod-e", 1, -600_000L, 0, 2, 30);     // saati 10 dk geri: örnek zamanı 11 dk önce görünür
        sample("pod-f-6666", "pod-f", 1, 100L, 0, 2, 30);
        sample("pod-f-7777", "pod-f", 0, 200L, 0, 2, 30);          // aynı ad, yeni süreç (konteyner yeniden başladı)

        List<WatchdogProbes.PodSample> live = probes().livePods(NOW);

        assertThat(live).extracting(WatchdogProbes.PodSample::pod)
                .containsExactlyInAnyOrder("pod-a", "pod-b", "pod-e", "pod-f (6666)", "pod-f (7777)");
    }

    // ── Saat uyumu (MP-37c) ──────────────────────────────────────────────────────────────────

    @Test
    @DisplayName("saat uyumu (inceleme W-4): önem pod'lar ARASI yayılımdan — ≤ 5 sn OK, 5–30 sn orta, > 30 sn yüksek; saati 10 dk geri "
            + "pod da okunur; TURU KAZANAN pod değil HER canlı pod")
    void clockSkewSpreadThresholds() {
        sample("pod-a-1111", "pod-a", 1, 400L, 0, 3, 30);
        sample("pod-b-2222", "pod-b", 1, -1_200L, 0, 2, 30);
        WatchdogProbes.Probe ok = probes().clockSkew(NOW);
        assertThat(ok.result()).isEqualTo(Result.OK);
        assertThat(ok.facts()).containsEntry("spread_ms", 1_600L).containsEntry("max_pod", "pod-a").containsEntry("min_pod", "pod-b");

        sample("pod-c-3333", "pod-c", 1, 12_000L, 0, 2, 30);
        WatchdogProbes.Probe warn = probes().clockSkew(NOW);
        assertThat(warn.result()).isEqualTo(Result.PROBLEM);
        assertThat(warn.severity()).isEqualTo("MEDIUM");
        assertThat(warn.facts()).containsEntry("spread_ms", 13_200L).containsEntry("max_pod", "pod-c").containsEntry("min_pod", "pod-b");
        assertThat(WatchdogMessages.detail(WatchdogCheck.CLOCK_SKEW, warn.facts(), false)).contains("pod-c ile pod-b", "13,2 sn fark");
        assertThat(WatchdogMessages.detail(WatchdogCheck.CLOCK_SKEW, warn.facts(), true)).contains("pod-c and pod-b", "13.2 s");

        sample("pod-e-5555", "pod-e", 1, -600_000L, 0, 2, 30);
        WatchdogProbes.Probe high = probes().clockSkew(NOW);
        assertThat(high.result()).isEqualTo(Result.PROBLEM);
        assertThat(high.severity()).isEqualTo("HIGH");
        assertThat(high.facts()).containsEntry("min_pod", "pod-e");
        @SuppressWarnings("unchecked")
        List<Map<String, Object>> pods = (List<Map<String, Object>>) high.facts().get("pods");
        assertThat(pods.get(0)).containsEntry("pod", "pod-e").containsKey("deviation_ms");
    }

    @Test
    @DisplayName("inceleme W-4: pod'lar uyumlu, veritabanı saati 40 sn farklı → sorun DEĞİL (bilgi olgusu); +16 / −16 sn pod'lar "
            + "(32 sn yayılım) → yüksek; tek pod → uyumlu")
    void databaseOffsetIsInformationalSpreadDecides() {
        sample("pod-a-1111", "pod-a", 1, 40_000L, 0, 3, 30);
        sample("pod-b-2222", "pod-b", 1, 40_400L, 0, 2, 30);
        WatchdogProbes.Probe offset = probes().clockSkew(NOW);
        assertThat(offset.result()).isEqualTo(Result.OK);
        assertThat(offset.facts()).containsEntry("db_offset_ms", 40_200L).containsEntry("spread_ms", 400L);
        assertThat(WatchdogMessages.detail(WatchdogCheck.CLOCK_SKEW, offset.facts(), false))
                .contains("birbiriyle uyumlu", "veritabanı saati pod'lardan 40,2 sn geride");

        mp.jdbc().update("DELETE FROM system_metric_samples");
        sample("pod-a-1111", "pod-a", 1, 16_000L, 0, 3, 30);
        sample("pod-b-2222", "pod-b", 1, -16_000L, 0, 2, 30);
        WatchdogProbes.Probe spread = probes().clockSkew(NOW);
        assertThat(spread.severity()).as("eski kural (|pod − DB| ≤ 16 sn) yalnız orta derdi").isEqualTo("HIGH");

        mp.jdbc().update("DELETE FROM system_metric_samples");
        sample("pod-a-1111", "pod-a", 1, 45_000L, 0, 3, 30);
        WatchdogProbes.Probe single = probes().clockSkew(NOW);
        assertThat(single.result()).isEqualTo(Result.OK);
        assertThat(WatchdogMessages.detail(WatchdogCheck.CLOCK_SKEW, single.facts(), false)).startsWith("Yalnız bir pod'un saati");
    }

    @Test
    @DisplayName("saat uyumu: fark bilinmiyor (eski sürüm pod) → UNKNOWN (sayaç değişmez); örnek yok → UNKNOWN; örnekleyici kapalı → NA")
    void clockSkewUnknownAndNotApplicable() {
        WatchdogProbes p = probes();
        WatchdogProbes.Probe none = p.clockSkew(NOW);
        assertThat(none.result()).isEqualTo(Result.UNKNOWN);
        assertThat(none.facts()).containsEntry("reason", "no_live_samples");

        sample("pod-old-1", "pod-old", 1, null, 0, 2, 30);          // 20.166.0 pod'u kolonu doldurmaz
        WatchdogProbes.Probe unknown = p.clockSkew(NOW);
        assertThat(unknown.result()).isEqualTo(Result.UNKNOWN);
        assertThat(unknown.facts()).containsEntry("reason", "skew_unknown").containsEntry("unknown_pods", 1);
        assertThat(WatchdogMessages.detail(WatchdogCheck.CLOCK_SKEW, unknown.facts(), false)).startsWith("Ölçülemedi");

        sample("pod-new-2", "pod-new", 1, 300L, 0, 2, 30);
        WatchdogProbes.Probe mixed = p.clockSkew(NOW);
        assertThat(mixed.result()).isEqualTo(Result.OK);
        assertThat(mixed.facts()).containsEntry("unknown_pods", 1);

        p.samplesEnabled = false;
        assertThat(p.clockSkew(NOW).result()).isEqualTo(Result.NA);
    }

