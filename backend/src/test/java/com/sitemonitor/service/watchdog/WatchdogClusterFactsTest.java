    @Test
    @DisplayName("örnekleyici kapalı ya da canlı pod örneği yok → karar değerlendiren pod'un kendi havuzu ve şema yamasıyla (etiketli)")
    void samplerOffFallsBackToEvaluatingPod() {
        when(db.current()).thenReturn(snapshot("UP", "UP", "UP", "DEGRADED", 0));
        WatchdogProbes off = probes();
        off.samplesEnabled = false;
        WatchdogProbes.Probe pool = off.database(NOW);
        assertThat(pool.result()).isEqualTo(Result.PROBLEM);
        assertThat(pool.facts()).containsEntry("decision_source", "evaluating_pod");
        assertThat((List<?>) pool.facts().get("pool_saturated_pods")).hasSize(1);
        assertThat(WatchdogMessages.detail(WatchdogCheck.DATABASE, pool.facts(), false)).contains("Pod örneği olmadığından");

        when(db.current()).thenReturn(snapshot("UP", "UP", "UP", "UP", 3));
        WatchdogProbes.Probe noSamples = probes().database(NOW);              // örnekleyici açık, canlı pod yok
        assertThat(noSamples.result()).isEqualTo(Result.PROBLEM);
        assertThat(noSamples.facts()).containsEntry("decision_source", "evaluating_pod");
        assertThat((List<?>) noSamples.facts().get("schema_failed_pods")).hasSize(1);
    }

    // ── İki pod sırayla değerlendirir — dalgalanma yok (MP-36) ───────────────────────────────

    @Test
    @DisplayName("turlar A, A, B, B, A, A: A'da açık push devresi + dolu havuz, B'de değil → durum hiç değişmez, bildirim gitmez")
    @SuppressWarnings("unchecked")
    void alternatingPodsDoNotFlap() {
        Map<String, WatchdogState> table = new LinkedHashMap<>();
        WatchdogStateRepository repo = mock(WatchdogStateRepository.class);
        when(repo.findAll()).thenAnswer(i -> new ArrayList<>(table.values()));
        when(repo.saveAll(any())).thenAnswer(i -> {
            for (WatchdogState s : (Collection<WatchdogState>) i.getArgument(0)) table.put(s.getCheckKey(), s);
            return null;
        });
        List<String> sent = new CopyOnWriteArrayList<>();
        sample("pod-a-1111", "pod-a", 0, 200L, 0, 5, 30);
        sample("pod-b-2222", "pod-b", 0, -300L, 0, 4, 30);

        UserPushService pushA = mock(UserPushService.class);
        when(pushA.enabled()).thenReturn(true);
        when(pushA.healthSnapshot()).thenReturn(Map.of("circuit_open", true));
        UserPushService pushB = mock(UserPushService.class);
        when(pushB.enabled()).thenReturn(true);
        when(pushB.healthSnapshot()).thenReturn(Map.of("circuit_open", false));
        DatabaseHealthService dbA = mock(DatabaseHealthService.class);
        when(dbA.current()).thenReturn(snapshot("UP", "UP", "UP", "DEGRADED", 1));
        DatabaseHealthService dbB = mock(DatabaseHealthService.class);
        when(dbB.current()).thenReturn(snapshot("UP", "UP", "UP", "UP", 0));

        WatchdogService a = watchdog(repo, pushA, dbA, sent, "A");
        WatchdogService b = watchdog(repo, pushB, dbB, sent, "B");
        Instant t = NOW;
        for (WatchdogService w : List.of(a, a, b, b, a, a)) {
            // Her pod dakikada bir örnek yazar (canlı kalır): örneksiz kalınca karar değerlendiren pod'a düşerdi (W-3 yedeği)
            for (String[] pod : new String[][]{{"pod-a-1111", "pod-a"}, {"pod-b-2222", "pod-b"}}) {
                mp.jdbc().update("INSERT INTO system_metric_samples(instance_id, pod_name, sampled_at, db_pending, db_active, db_max, "
                        + "clock_skew_ms, schema_failed_patches) VALUES (?,?,?,0,4,30,200,0)", pod[0], pod[1],
                        WatchdogTransition.ISO.format(t.truncatedTo(ChronoUnit.MINUTES)));
            }
            w.evaluate(t, true);
            t = t.plusSeconds(60);
        }
        assertThat(table.get("push_outbox").getStatus()).isEqualTo("OK");
        assertThat(table.get("push_outbox").getProblemStreak()).isZero();
        assertThat(table.get("database").getStatus()).isEqualTo("OK");
        assertThat(table.get("clock_skew").getStatus()).isEqualTo("OK");
        assertThat(sent).as("pod'a özgü olgular bildirim üretmez").isEmpty();
    }

    WatchdogService watchdog(WatchdogStateRepository repo, UserPushService push, DatabaseHealthService dbh, List<String> sent, String name) {
        WatchdogProbes p = new WatchdogProbes(mp.jdbc(), settings);
        p.setPush(push);
        p.setDatabase(dbh);
        WatchdogNotifier notifier = mock(WatchdogNotifier.class);
        when(notifier.send(anyList(), anyBoolean())).thenAnswer(i -> {
            List<WatchdogMail.Item> items = i.getArgument(0);
            for (WatchdogMail.Item it : items) sent.add(name + ":" + it.kind() + ":" + it.label());
            return new WatchdogNotifier.Report(WatchdogNotifier.Outcome.DELIVERED, "SENT", "SKIPPED", "SKIPPED", 1);
        });
        return new WatchdogService(repo, p, notifier, settings);
    }
