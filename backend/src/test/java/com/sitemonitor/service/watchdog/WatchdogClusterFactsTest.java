    @Test
    @DisplayName("ölü push ağ geçidi: satırlar takılmadan FAILED olur — son 30 dk'nın sonuç oranı sorun açar (test gönderimi ve eski "
            + "satır sayılmaz); devre kesici kapalı pod'da da")
    void deadPushGatewayIsDetectedClusterWide() {
        UserPushService push = mock(UserPushService.class);
        when(push.enabled()).thenReturn(true);
        when(push.healthSnapshot()).thenReturn(Map.of("circuit_open", false));
        WatchdogProbes p = probes();
        p.setPush(push);
        for (int i = 0; i < 4; i++) push("FAILED", "OPEN", 5);
        push("SENT", "OPEN", 6);
        for (int i = 0; i < 5; i++) push("FAILED", "TEST", 3);      // test gönderimi — sayılmaz
        for (int i = 0; i < 9; i++) push("SENT", "OPEN", 45);       // pencere dışı — sayılmaz
        WatchdogProbes.Probe down = p.pushOutbox(NOW);
        assertThat(down.result()).isEqualTo(Result.PROBLEM);
        assertThat(down.facts()).containsEntry("recent_failed", 4L).containsEntry("recent_sent", 1L).containsEntry("stuck", 0L);
        assertThat(WatchdogMessages.detail(WatchdogCheck.PUSH_OUTBOX, down.facts(), false)).contains("5 push'un 4'i gönderilemedi");

        for (int i = 0; i < 4; i++) push("SENT", "OPEN", 2);
        assertThat(p.pushOutbox(NOW).result()).as("4 / 9 < %50").isEqualTo(Result.OK);
    }

